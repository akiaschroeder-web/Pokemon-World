// Pokémon World (web build): Unova's 3D maps.
//
// In Unova the field map isn't drawn by the GBA background layers: the page draws Pokémon Black's
// real 3D map (platform/web/unova3d.js) and the game's picture goes on top with its empty parts
// transparent. Sprites that belong to the map (people, Pokémon, field effects: the ones that move
// with the camera) are taken out of the 2D picture and given to the page with their pixels and
// screen positions, so it can stand them up inside the 3D scene. Menus, text and weather stay 2D.
//
// Each frame (Web3D_EndFrame) fills sScene, which the page reads through Web_Get3DScene().

