#!/usr/bin/env python3
"""Pokémon World: Heart & Soul's overworld (object event) sprites, for import_hns.py.

Heart & Soul (used with permission, see PROJECT_CREDITS.md) has overworld sprites we don't:
Johto's gym leaders, Elm, Kurt, Silver, the Rocket executives, the Red Gyarados, ... Its maps
and scripts keep their Heart & Soul names as OBJ_EVENT_GFX_HNS_<NAME> (import_hns.py's gfx()).
For each of those, gen_object_sprites() either
  - reuses one of our sprites when it looks the same in game (same size and, pixel for pixel,
    the same colours: our picture with our palette vs. Heart & Soul's picture with its palette),
    and then OBJ_EVENT_GFX_HNS_<NAME> is a #define in constants/hns_compat.h (gen_compat), or
  - brings Heart & Soul's sprite over, with Heart & Soul's own graphics info (size, anims, shadow,
    inanimate, tracks) as an OBJ_EVENT_GFX_HNS_<NAME> entry of the object event enum.
Palettes: one tag per Heart & Soul palette file (sprites sharing one in Heart & Soul share it
here), loaded by tag like Proyecto Sinnoh's; a palette with exactly the colours of one of ours
uses our tag instead.

What it writes (all generated, rewritten on every run):
  include/constants/event_objects.h       OBJ_EVENT_GFX_HNS_* between "// BEGIN HNS_OBJ_EVENT_GFX"
                                           and "// END", OBJ_EVENT_PAL_TAG_HNS_* between
                                           "// BEGIN HNS_OBJ_EVENT_PAL_TAGS" and "// END"
  src/data/object_events/object_event_graphics_hns.h          pics and palettes (INCGFX)
  src/data/object_events/object_event_pic_tables_hns.h        frame tables
  src/data/object_events/object_event_graphics_info_hns.h     ObjectEventGraphicsInfo (+ anim
                                                              tables we don't have, if any)
  src/data/object_events/object_event_graphics_info_pointers_hns{,_extern}.h
  src/data/object_events/object_event_palettes_hns.h          sObjectEventSpritePalettes entries
  graphics/object_events/pics/hns/, graphics/object_events/palettes/hns/   copied from Heart & Soul
Each *_hns.h is #included from its non-_hns counterpart (or event_object_movement.c).

Standalone (regenerates the sprites for the given Heart & Soul names, without the full import):
    python3 tools/pokemon_world/hns_sprites.py [--hns ~/ref/pokemonHnS] OBJ_EVENT_GFX_KURT ...
"""
import argparse, functools, hashlib, json, os, re, shutil, struct, sys, zlib

GEN_C = "// Generated by tools/pokemon_world/import_hns.py (hns_sprites.py) - edit that script, not this file.\n"
D = "src/data/object_events"
PIC_DIR = "graphics/object_events/pics/hns"
PAL_DIR = "graphics/object_events/palettes/hns"
PAL_TAG_BASE = 0x1F10   # free: Proyecto Sinnoh uses 0x1200-0x126C, Lucas/Dawn 0x1F00-0x1F04
STATE_KEY = "object_sprite_files"
INFO_FIELDS = ["tileTag", "paletteTag", "reflectionPaletteTag", "size", "width", "height", "paletteSlot",
               "shadowSize", "inanimate", "compressed", "tracks", "oam", "subspriteTables", "anims", "images",
               "affineAnims"]
PREFIX = "OBJ_EVENT_GFX_"


def rd(p):
    return open(p, encoding="utf-8", errors="replace").read()


def wr(p, s):
    os.makedirs(os.path.dirname(p) or ".", exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(s)


def splice(path, tag, text):
    s = rd(path)
    m = re.search(r"(?m)^[ \t]*// BEGIN " + re.escape(tag) + r"[^\n]*\n(.*?)^[ \t]*// END " + re.escape(tag), s, re.S)
    if not m:
        sys.exit(f"{path}: no '// BEGIN {tag}' ... '// END {tag}' block")
    wr(path, s[:m.start(1)] + text + s[m.end(1):])


def camel(s):
    return "".join(w[:1].upper() + w[1:].lower() for w in re.split(r"_+", s) if w)


# --- pictures and palettes ------------------------------------------------------------------

def png_size(path):
    d = open(path, "rb").read(24)
    if d[:8] != b"\x89PNG\r\n\x1a\n":
        return None
    return struct.unpack(">II", d[16:24])


@functools.lru_cache(maxsize=None)
def png_indices(path):
    """(width, height, rows of colour indices) of an indexed PNG (4 or 8 bits)."""
    d = open(path, "rb").read()
    i, idat = 8, b""
    while i < len(d):
        n, t = struct.unpack(">I4s", d[i:i + 8])
        c = d[i + 8:i + 8 + n]
        i += 12 + n
        if t == b"IHDR":
            w, h, bd, ct = struct.unpack(">IIBB", c[:10])
        elif t == b"IDAT":
            idat += c
    if ct != 3 or bd not in (4, 8):
        raise ValueError(f"{path}: not a 4/8-bit indexed PNG")
    raw = zlib.decompress(idat)
    stride = (w * bd + 7) // 8
    prev, k, rows = bytearray(stride), 0, []
    for _ in range(h):
        f, line = raw[k], bytearray(raw[k + 1:k + 1 + stride])
        k += 1 + stride
        for x in range(stride):
            a = line[x - 1] if x else 0
            b = prev[x]
            cc = prev[x - 1] if x else 0
            if f == 1:
                line[x] = (line[x] + a) & 255
            elif f == 2:
                line[x] = (line[x] + b) & 255
            elif f == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - cc
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - cc)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else cc)) & 255
        prev = line
        rows.append(tuple(line[:w]) if bd == 8 else tuple((line[x // 2] >> (4 * (1 - x % 2))) & 15 for x in range(w)))
    return w, h, tuple(rows)


@functools.lru_cache(maxsize=None)
def pal_colours(path):
    """The 16 colours of a JASC .pal, as the GBA sees them (5 bits per channel)."""
    lines = rd(path).split()
    if lines[:1] != ["JASC-PAL"]:
        raise ValueError(f"{path}: not a JASC palette")
    n = int(lines[2])
    v = [int(x) for x in lines[3:3 + 3 * n]]
    cols = [tuple(c >> 3 for c in v[j:j + 3]) for j in range(0, len(v), 3)]
    return tuple((cols + [(0, 0, 0)] * 16)[:16])


@functools.lru_cache(maxsize=None)
def look(png, pal):
    """A hash of how a picture looks in game with that palette (index 0 = transparent)."""
    w, h, rows = png_indices(png)
    cols = pal_colours(pal)
    return hashlib.sha1(repr((w, h, [[None if v == 0 else cols[v & 15] for v in r] for r in rows])).encode()).hexdigest()


# --- reading the object event tables (ours and Heart & Soul's) ---------------------------------

def parse_tables(root, inc):
    """Pointers, graphics info, pic tables, graphics files and palette tags of one project."""
    t = {}
    t["ptr"] = dict(re.findall(r"\[(OBJ_EVENT_GFX_\w+)\]\s*=\s*&(gObjectEventGraphicsInfo_\w+)",
                               rd(f"{root}/{D}/object_event_graphics_info_pointers.h")))
    t["info"] = {}
    for m in re.finditer(r"const struct ObjectEventGraphicsInfo (gObjectEventGraphicsInfo_\w+)\s*=\s*\{(.*?)\};",
                         rd(f"{root}/{D}/object_event_graphics_info.h"), re.S):
        body = re.sub(r"//[^\n]*", "", m.group(2))
        if "." in body.split(",")[0]:
            f = dict(re.findall(r"\.(\w+)\s*=\s*([^,]+?)\s*(?:,|$)", body))
        else:
            f = dict(zip(INFO_FIELDS, [x.strip() for x in body.split(",") if x.strip()]))
        t["info"][m.group(1)] = f
    t["pics"] = {m.group(1): m.group(2) for m in re.finditer(
        r"static const struct SpriteFrameImage (sPicTable_\w+)\[\]\s*=\s*\{(.*?)\};",
        rd(f"{root}/{D}/object_event_pic_tables.h"), re.S)}
    t["files"] = {s: f for s, f in re.findall(inc, rd(f"{root}/{D}/object_event_graphics.h"))}
    t["pal"] = {}
    for sym, tag in re.findall(r"\{\s*(gObjectEventPal\w*),\s*(OBJ_EVENT_PAL_TAG_\w+)\s*\}",
                               rd(f"{root}/src/event_object_movement.c")):
        t["pal"].setdefault(tag, sym)
    t["anims"] = rd(f"{root}/{D}/object_event_anims.h")
    return t


@functools.lru_cache(maxsize=None)
def hns_tables(H):
    t = parse_tables(H, r"(gObjectEvent\w+)\[\]\s*=\s*INCBIN_U\d+\(\"([^\"]+)\"")
    t["rules"] = rd(f"{H}/spritesheet_rules.mk")
    return t


@functools.lru_cache(maxsize=None)
def available(H):
    """Heart & Soul's object sprite constants (the ones it has graphics info for)."""
    t = hns_tables(H)
    return frozenset(g for g, ip in t["ptr"].items() if ip in t["info"])


def our_tables():
    return parse_tables(".", r"(gObjectEvent\w+)\[\]\s*=\s*INCGFX_U\d+\(\"([^\"]+)\"")


def pic_syms(table_body):
    out = []
    for s in re.findall(r"\b(gObjectEventPic_\w+)", table_body):
        if s not in out:
            out.append(s)
    return out


def anim_table(text, name):
    m = re.search(r"\b" + re.escape(name) + r"\[\]\s*=\s*\{(.*?)\};", text, re.S)
    return m and m.group(1)


def norm(s):
    return re.sub(r"\s+", "", re.sub(r"//[^\n]*", "", s))


def resolve_anims(name, ht, ot, extra, note):
    """Our anim table for Heart & Soul's `name`: ours of that name, or one of ours with the same
    entries and frames, or a copy of Heart & Soul's (sAnim*_Hns) in `extra`."""
    if anim_table(ot["anims"], name) is not None:
        return name
    body = anim_table(ht["anims"], name)
    if body is None:
        note("object sprites: anim tables not found (used sAnimTable_Standard)", name)
        return "sAnimTable_Standard"
    subs = sorted(set(re.findall(r"=\s*(sAnim_\w+)", body)))
    same_subs = all(anim_table(ot["anims"], s) is not None and
                    norm(anim_table(ot["anims"], s)) == norm(anim_table(ht["anims"], s) or "") for s in subs)
    if same_subs:
        for m in re.finditer(r"static const union AnimCmd \*const (sAnimTable_\w+)\[\]\s*=\s*\{(.*?)\};", ot["anims"], re.S):
            if norm(m.group(2)) == norm(body):
                note("object sprites: Heart & Soul anim tables that are one of ours", f"{name} = {m.group(1)}")
                return m.group(1)
    new = name + "_Hns"
    if new not in extra:
        text = body
        for s in subs:
            ob, hb = anim_table(ot["anims"], s), anim_table(ht["anims"], s)
            if ob is not None and norm(ob) == norm(hb or ""):
                continue
            text = re.sub(r"\b" + s + r"\b", s + "_Hns", text)
            extra[s + "_Hns"] = f"static const union AnimCmd {s}_Hns[] = {{{hb}}};\n\n"
        extra[new] = f"static const union AnimCmd *const {new}[] = {{{text}}};\n\n"
        note("object sprites: Heart & Soul anim tables copied", new)
    return new


# --- the generator ------------------------------------------------------------------------------

def gen_object_sprites(H, names, state, new_state, note):
    """names: Heart & Soul OBJ_EVENT_GFX_* constants our maps/scripts use (as OBJ_EVENT_GFX_HNS_*).
    Returns {Heart & Soul name: our constant} - OBJ_EVENT_GFX_HNS_<NAME> for the ones brought over,
    one of ours for the ones that are the same sprite (gen_compat #defines those)."""
    for old in state.get(STATE_KEY, []):
        if os.path.exists(old):
            os.remove(old)
    ht, ot = hns_tables(H), our_tables()

    # ours: (sprite width, height, look) -> our constants
    def our_png(sym):
        f = ot["files"].get(sym)
        return f if f and f.endswith(".png") and os.path.exists(f) else None

    def our_pal(tag):
        f = ot["files"].get(ot["pal"].get(tag, ""))
        return f if f and f.endswith(".pal") and os.path.exists(f) else None

    our_pals = {}   # colours -> our tag (the NPC palettes first: e.g. Ho-Oh's has the same colours as NPC_BLUE)
    for i, tag in sorted(enumerate(ot["pal"]), key=lambda it: ("_NPC_" not in it[1], "REFLECTION" in it[1], it[0])):
        f = our_pal(tag)
        if f and not tag.startswith("OBJ_EVENT_PAL_TAG_HNS_"):
            our_pals.setdefault(pal_colours(f), tag)

    def our_same(w, h, png, key):
        size = png_size(png)
        hits = []
        for g, ip in ot["ptr"].items():
            f = ot["info"].get(ip)
            if not f or g.startswith("OBJ_EVENT_GFX_HNS_") or (f.get("width"), f.get("height")) != (w, h):
                continue
            syms = pic_syms(ot["pics"].get(f.get("images", ""), ""))
            p, pal = syms and our_png(syms[0]), our_pal(f.get("paletteTag", ""))
            if len(syms) == 1 and p and pal and png_size(p) == size and look(p, pal) == key:
                hits.append(g)
        return sorted(hits)

    result, new = {}, []
    pics, pals = {}, {}      # Heart & Soul file -> (our file, symbol); Heart & Soul .pal -> (our file or None, sym, tag)
    for g in names:
        base = g[len(PREFIX):]
        f = ht["info"].get(ht["ptr"].get(g, ""))
        if not f:
            note("object sprites Heart & Soul has no graphics for (became OBJ_EVENT_GFX_BOY_1)", g)
            result[g] = "OBJ_EVENT_GFX_BOY_1"
            continue
        syms = pic_syms(ht["pics"].get(f["images"], ""))
        srcs = [ht["files"].get(s, "").replace(".4bpp", ".png") for s in syms]
        palsym = ht["pal"].get(f["paletteTag"])
        palsrc = palsym and ht["files"].get(palsym, "").replace(".gbapal", ".pal")
        if not syms or not all(os.path.exists(f"{H}/{s}") for s in srcs) or not palsrc or not os.path.exists(f"{H}/{palsrc}"):
            note("object sprites whose Heart & Soul graphics weren't found (became OBJ_EVENT_GFX_BOY_1)", g)
            result[g] = "OBJ_EVENT_GFX_BOY_1"
            continue
        if len(syms) == 1:
            same = our_same(f["width"], f["height"], f"{H}/{srcs[0]}", look(f"{H}/{srcs[0]}", f"{H}/{palsrc}"))
            if same:
                best = sorted(same, key=lambda c: (c != g, c.endswith("_FRLG"), c))[0]
                result[g] = best
                note("object sprites reused from ours (same picture and colours as Heart & Soul's)", f"{g} -> {best}")
                continue
        for s, src in zip(syms, srcs):
            if src not in pics:
                pics[src] = (f"{PIC_DIR}/{base.lower()}.png" if len(syms) == 1 else
                             f"{PIC_DIR}/{base.lower()}_{len(pics)}.png", "gObjectEventPic_Hns" + camel(base) +
                             ("" if len(syms) == 1 else s[len("gObjectEventPic_"):]))
            if max(max(r) for r in png_indices(f"{H}/{src}")[2]) > 15:
                note("object sprites with colours past index 15 (check the picture)", src)
        if palsrc not in pals:
            ours = our_pals.get(pal_colours(f"{H}/{palsrc}"))
            pb = os.path.basename(palsrc)[:-4]
            if ours:
                pals[palsrc] = (None, None, ours)
                note("object sprite palettes that are one of ours", f"{palsrc} -> {ours}")
            else:
                pals[palsrc] = (f"{PAL_DIR}/{pb}.pal", "gObjectEventPal_Hns" + camel(pb),
                                "OBJ_EVENT_PAL_TAG_HNS_" + re.sub(r"\W", "_", pb).upper())
        new.append((g, base, f, syms, srcs, palsrc))
        result[g] = "OBJ_EVENT_GFX_HNS_" + base
        note("object sprites brought over from Heart & Soul", f"OBJ_EVENT_GFX_HNS_{base} <- {', '.join(srcs)}")

    # copy the pictures and palettes
    written = []
    for src, (dst, _) in pics.items():
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy(f"{H}/{src}", dst)
        written.append(dst)
    for src, (dst, _, _) in pals.items():
        if dst:
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy(f"{H}/{src}", dst)
            written.append(dst)
    new_state[STATE_KEY] = written

    def gfx_args(src):
        m = re.search(r"(?m)^\$\(OBJEVENTGFXDIR\)/" + re.escape(src[len("graphics/object_events/pics/"):-4]) +
                      r"\.4bpp:[^\n]*\n\t\$\(GFX\) \$< \$@ ([^\n]*)", ht["rules"])
        return f', "{m.group(1).strip()}"' if m else ""

    hdr = "// Heart & Soul's overworld sprites (graphics/object_events/pics/hns, palettes/hns).\n"
    gfx = [GEN_C, hdr, "// Included from object_event_graphics.h.\n"]
    for src, (dst, sym) in pics.items():
        gfx.append(f'const u32 {sym}[] = INCGFX_U32("{dst}", ".4bpp"{gfx_args(src)});\n')
    tags, paltab = [], [GEN_C, "// Heart & Soul's sprite palettes. Included inside sObjectEventSpritePalettes.\n"]
    n = 0
    for src, (dst, sym, tag) in sorted(pals.items(), key=lambda kv: kv[1][2]):
        if not dst:
            continue
        gfx.append(f'const u16 {sym}[] = INCGFX_U16("{dst}", ".gbapal");\n')
        tags.append(f"#define {tag:<45} 0x{PAL_TAG_BASE + n:04X}\n")
        paltab.append(f"    {{{sym}, {tag}}},\n")
        n += 1

    pt = [GEN_C, hdr, "// Included from object_event_pic_tables.h.\n"]
    info_extra, infos, enum, ext, ptrs = {}, [], [], [GEN_C, hdr], [GEN_C, hdr, "// Included inside gObjectEventGraphicsInfoPointers.\n"]
    for g, base, f, syms, srcs, palsrc in sorted(new, key=lambda x: x[1]):
        c = "Hns" + camel(base)
        body = ht["pics"][f["images"]]
        for s, src in zip(syms, srcs):
            body = re.sub(r"\b" + s + r"\b", pics[src][1], body)
        pt.append(f"static const struct SpriteFrameImage sPicTable_{c}[] = {{{body}}};\n\n")
        for field in ("oam", "subspriteTables"):
            nm = f[field].lstrip("&")
            if not re.search(r"\b" + re.escape(nm) + r"\b", rd(f"{D}/base_oam.h") + rd(f"{D}/object_event_subsprites.h")):
                note("object sprites: Heart & Soul oam/subsprite tables we don't have", f"{g}: {nm}")
        anims = resolve_anims(f["anims"], ht, ot, info_extra, note)
        slot = "PALSLOT_NPC_SPECIAL" if f["paletteSlot"] == "10" else "PALSLOT_NPC_1"
        infos.append(
            f"const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_{c} = {{\n"
            f"    .tileTag = TAG_NONE,\n"
            f"    .paletteTag = {pals[palsrc][2]},\n"
            f"    .reflectionPaletteTag = OBJ_EVENT_PAL_TAG_NONE,\n"
            f"    .size = {f['size']},\n    .width = {f['width']},\n    .height = {f['height']},\n"
            f"    .paletteSlot = {slot},\n"
            f"    .shadowSize = {f['shadowSize']},\n"
            f"    .inanimate = {f['inanimate']},\n"
            f"    .compressed = FALSE,\n"
            f"    .tracks = {f['tracks']},\n"
            f"    .oam = {f['oam']},\n"
            f"    .subspriteTables = {f['subspriteTables']},\n"
            f"    .anims = {anims},\n"
            f"    .images = sPicTable_{c},\n"
            f"    .affineAnims = gDummySpriteAffineAnimTable,\n}};\n\n")
        enum.append(f"    OBJ_EVENT_GFX_HNS_{base},\n")
        ext.append(f"extern const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_{c};\n")
        ptrs.append(f"    [OBJ_EVENT_GFX_HNS_{base}] = &gObjectEventGraphicsInfo_{c},\n")

    splice("include/constants/event_objects.h", "HNS_OBJ_EVENT_GFX", "".join(enum))
    splice("include/constants/event_objects.h", "HNS_OBJ_EVENT_PAL_TAGS", "".join(tags))
    wr(f"{D}/object_event_graphics_hns.h", "".join(gfx))
    wr(f"{D}/object_event_pic_tables_hns.h", "".join(pt).rstrip("\n") + "\n")
    wr(f"{D}/object_event_graphics_info_hns.h", "".join([GEN_C, hdr, "// Included from object_event_graphics_info.h.\n\n"]
                                                       + list(info_extra.values()) + infos).rstrip("\n") + "\n")
    wr(f"{D}/object_event_graphics_info_pointers_hns_extern.h", "".join(ext))
    wr(f"{D}/object_event_graphics_info_pointers_hns.h", "".join(ptrs))
    wr(f"{D}/object_event_palettes_hns.h", "".join(paltab))
    return result


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--hns", default=os.path.expanduser("~/ref/pokemonHnS"))
    ap.add_argument("names", nargs="+")
    a = ap.parse_args()
    STATE = "tools/pokemon_world/hns_import_state.json"
    st = json.load(open(STATE)) if os.path.exists(STATE) else {}
    ns = dict(st)
    rep = {}
    res = gen_object_sprites(a.hns, a.names, st, ns, lambda k, w: rep.setdefault(k, set()).add(w))
    json.dump(ns, open(STATE, "w"), indent=1)
    open(STATE, "a").write("\n")
    for k, v in rep.items():
        print(f"{k}:")
        for w in sorted(v):
            print("   ", w)
    print(json.dumps(res, indent=1))
