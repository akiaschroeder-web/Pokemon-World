"""Pokémon World: Pokémon Black's own key items, which the expansion doesn't have.

Their names and descriptions are Black's (a/0/0/2 files 54 and 53); their icons are Black's
(a/0/2/5: NCGR + NCLR pairs, 32x32 - the drawing is cropped to our 24x24). They're added after
ITEM_HM09 (include/constants/items.h, block UNOVA_ITEMS), so no item ids move:
  src/data/items_unova.h                     their gItemsInfo entries (included in src/data/items.h)
  src/data/graphics/items_unova.h            their icons (included in src/data/graphics/items.h)
  include/items_unova_icons.h                the icons' declarations
  graphics/items/icons/unova/*.png
Returns {BW item id: ITEM_ constant} for the BW script interpreter's item table.
"""

import os
import re
import struct

import sprites

ICON_DIR = 'graphics/items/icons/unova'
# BW item id -> (our constant, icon NCGR file in a/0/2/5); the Xtransceiver has a second id (her colour)
NEW = [
    (574, 'ITEM_LIBERTY_PASS', 965), (575, 'ITEM_PASS_ORB', 827), (578, 'ITEM_PROP_CASE', 817),
    (579, 'ITEM_DRAGON_SKULL', 819), (616, 'ITEM_LIGHT_STONE', 821), (617, 'ITEM_DARK_STONE', 823),
    (621, 'ITEM_XTRANSCEIVER', 825), (623, 'ITEM_GRAM_1', 829), (624, 'ITEM_GRAM_2', 829),
    (625, 'ITEM_GRAM_3', 829),
]
ALIASES = {626: 'ITEM_XTRANSCEIVER'}
FIRST_ID = 899         # after ITEM_HM09 = 898


def u16(b, o): return struct.unpack_from('<H', b, o)[0]


def icon(files, n):
    """32x32 NCGR n with the next NCLR -> (24x24 indices, palette)."""
    g = files[n]
    off = struct.unpack_from('<I', g, 16 + 28)[0]
    pd = g[16 + 8 + off:]
    idx = bytearray(32 * 32)
    for t in range(16):
        tx, ty = t % 4, t // 4
        for y in range(8):
            for x in range(8):
                b = pd[t * 32 + y * 4 + x // 2]
                idx[(ty * 8 + y) * 32 + tx * 8 + x] = (b >> 4) if x & 1 else (b & 15)
    j = n + 1
    while not files[j].startswith(b'RLCN'):
        j += 1
    pal = [u16(files[j], 16 + 0x18 + 2 * c) for c in range(16)]
    # crop to 24x24 around the drawing
    xs = [i % 32 for i in range(1024) if idx[i]] or [12]
    ys = [i // 32 for i in range(1024) if idx[i]] or [12]
    cx = max(0, min(8, (min(xs) + max(xs) + 1) // 2 - 12))
    cy = max(0, min(8, (min(ys) + max(ys) + 1) // 2 - 12))
    out = bytes(idx[(cy + y) * 32 + cx + x] for y in range(24) for x in range(24))
    return out, pal


def wrap(text, width=18, lines=3):
    words, out, cur = text.split(), [], ''
    for w in words:
        if cur and len(cur) + 1 + len(w) > width:
            out.append(cur)
            cur = w
        else:
            cur = (cur + ' ' + w).strip()
    if cur:
        out.append(cur)
    return '\\n'.join(out[:lines])


def write(rom, decode_text, plain):
    names = [plain(s) for s in decode_text(rom.narc('a/0/0/2')[54])]
    descs = [plain(s).replace('\n', ' ') for s in decode_text(rom.narc('a/0/0/2')[53])]
    files = rom.narc('a/0/2/5')
    os.makedirs(ICON_DIR, exist_ok=True)
    enum, data, gfx, ext = [], [], [], []
    consts = {}
    seen = set()
    for k, (bw, const, ncgr) in enumerate(NEW):
        consts[bw] = const
        base = const[len('ITEM_'):].lower()
        camel = ''.join(p.title() for p in base.split('_'))
        enum.append('    %s = %d,\n' % (const, FIRST_ID + k))
        if ncgr not in seen:
            seen.add(ncgr)
            idx, pal = icon(files, ncgr)
            sprites.png_indexed('%s/%s.png' % (ICON_DIR, base), 24, 24, [idx], pal)
        icon_name = {829: 'gram_1'}.get(ncgr, base)
        icon_camel = ''.join(p.title() for p in icon_name.split('_'))
        if icon_name == base:
            path = '%s/%s.png' % (ICON_DIR, base)
            gfx.append('const u32 gItemIcon_%s_Bw[] = INCGFX_U32("%s", ".4bpp.smol");\n'
                       'const u16 gItemIconPalette_%s_Bw[] = INCGFX_U16("%s", ".gbapal");\n' % (camel, path, camel, path))
            ext.append('extern const u32 gItemIcon_%s_Bw[];\nextern const u16 gItemIconPalette_%s_Bw[];\n' % (camel, camel))
        desc = re.sub(r'\s+', ' ', descs[bw]).strip().replace('"', "'")
        data.append('    [%s] =\n    {\n        .name = ITEM_NAME("%s"),\n        .price = 0,\n'
                    '        .description = COMPOUND_STRING("%s"),\n        .importance = 1,\n'
                    '        .pocket = POCKET_KEY_ITEMS,\n        .type = ITEM_USE_BAG_MENU,\n'
                    '        .fieldUseFunc = ItemUseOutOfBattle_CannotUse,\n'
                    '        .iconPic = gItemIcon_%s_Bw,\n        .iconPalette = gItemIconPalette_%s_Bw,\n    },\n'
                    % (const, names[bw], wrap(desc), icon_camel, icon_camel))
    consts.update(ALIASES)
    last = NEW[-1][1]
    hdr = '// Generated by tools/pokemon_world/bw/items.py - edit that script, not this file.\n'
    with open('src/data/items_unova.h', 'w', encoding='utf-8') as f:
        f.write(hdr + "// Pokémon Black's key items. Included inside gItemsInfo.\n" + ''.join(data))
    with open('src/data/graphics/items_unova.h', 'w', encoding='utf-8') as f:
        f.write(hdr + ''.join(gfx))
    with open('include/items_unova_icons.h', 'w', encoding='utf-8') as f:
        f.write(hdr + '#ifndef GUARD_ITEMS_UNOVA_ICONS_H\n#define GUARD_ITEMS_UNOVA_ICONS_H\n' + ''.join(ext) + '#endif\n')
    p = 'include/constants/items.h'
    s = open(p, encoding='utf-8').read()
    block = ("    // BEGIN UNOVA_ITEMS: Pokémon World, Pokémon Black's key items (generated by tools/pokemon_world/bw/items.py)\n"
             + ''.join(enum) + '    // END UNOVA_ITEMS\n')
    if '// BEGIN UNOVA_ITEMS' in s:
        i = s.index('    // BEGIN UNOVA_ITEMS')
        j = s.index('    // END UNOVA_ITEMS\n') + len('    // END UNOVA_ITEMS\n')
        s = s[:i] + block + s[j:]
    else:
        i = s.index('\n    ITEMS_COUNT = ') + 1
        s = s[:i] + block + '\n' + s[i:]
    s = re.sub(r'ITEMS_COUNT = ITEM_\w+ \+ 1,', 'ITEMS_COUNT = %s + 1,' % last, s)
    open(p, 'w', encoding='utf-8').write(s)
    print('items: %d of Black\'s key items added' % len(NEW))
    return consts


def write_pockets(rom):
    """src/data/bw_item_pockets.h: each BW item's bag pocket, from its item data (a/0/2/4: 36 bytes
    per item; bits 7-10 of the u16 at 8 - checked on Potion 1, Poké Ball 0, Oran Berry 3, TM01 2,
    Town Map 4), for ItemGetPocket."""
    data = rom.narc('a/0/2/4')
    pockets = [((d[8] | d[9] << 8) >> 7) & 15 if len(d) >= 10 else 0 for d in data]
    with open('src/data/bw_item_pockets.h', 'w') as f:
        f.write('// Generated by tools/pokemon_world/bw/items.py: Pokémon Black item id -> its bag pocket\n'
                '// (0 items, 1 medicine, 2 TMs & HMs, 3 berries, 4 key items).\n')
        f.write('static const u8 sBwItemPocket[%d] = {%s};\n' % (len(pockets), ', '.join(map(str, pockets))))
