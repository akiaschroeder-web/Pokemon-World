"""Pokémon World: BW's map replacements driven by the story (MapReplaceSetEvent), e.g. the player's
room after the first battle.

a/0/1/0 file 0: 16-byte entries - u16 matrix, u8 kind (1 = the whole matrix is swapped, 0 = one
chunk in it), u8 condition, u16 values[5], u16 0xFFFF. Conditions 0 (season) and 1 (game version)
are resolved by the converter already; condition n >= 3 is MapReplace event n - 3 (from where
the scripts set them: Nuvema's room is event 6 -> condition 9 -> matrix 40 becomes 242). For a
matrix swap values[1] is the new matrix; for a chunk swap values[0] is the chunk and values[1]
its replacement (format after CTRMapV's VMapReplaceTable).

Each replacement is written as its own matrix file, unova/matrices/m<id>.json, with its chunks
converted like the zone's own (same area, so the same textures); id is the replacement matrix,
or 1000 + table index for a chunk swap. src/data/bw_map_replace.h lists them for web3d.c:
{event id, matrix, matrix to draw instead}.
"""

import json
import os
import struct

FIRST_EVENT_CONDITION = 3
CHUNK_SWAP_BASE = 1000


def entries(rom):
    d = rom.narc('a/0/1/0')[0]
    out = []
    for i in range(0, len(d) - 15, 16):
        mtx, kind, cond = struct.unpack_from('<HBB', d, i)
        vals = struct.unpack_from('<5H', d, i + 4)
        if cond >= FIRST_EVENT_CONDITION:
            out.append((i // 16, mtx, kind, cond - FIRST_EVENT_CONDITION, vals))
    return out


def write(rom, conv, zones, out_dir, u16, u32):
    """conv: import_bw.Converter (its chunk(cid, zone) exports a chunk); zones: import_bw.Zone list."""
    table = []
    # chunk swaps of one event in one matrix make one replacement matrix together
    jobs, swaps = [], {}
    for idx, mtx, kind, event, vals in entries(rom):
        if kind == 1:
            jobs.append((idx, mtx, kind, event, vals[1], None))
        elif (mtx, event) in swaps:
            swaps[(mtx, event)][vals[0]] = vals[1]
        else:
            swaps[(mtx, event)] = {vals[0]: vals[1]}
            jobs.append((idx, mtx, kind, event, CHUNK_SWAP_BASE + idx, swaps[(mtx, event)]))
    for idx, mtx, kind, event, new_id, swap in jobs:
        zone = next((z for z in zones if z.matrix == mtx), None)
        if zone is None:
            continue
        if kind == 1:
            m = rom.narc('a/0/0/9')[new_id]
            w, h = u16(m, 4), u16(m, 6)
            cells = list(struct.unpack_from('<%di' % (w * h), m, 8))
        else:
            # the matrix as converted, with only the swapped chunks converted anew (each with the
            # zone that owns its cell, for that zone's textures)
            m = rom.narc('a/0/0/9')[mtx]
            w, h = u16(m, 4), u16(m, 6)
            orig = struct.unpack_from('<%di' % (w * h), m, 8)
            names = list(json.load(open('%s/matrices/m%d.json' % (out_dir, mtx)))['cells'])
            for i, c in enumerate(orig):
                if c in swap:
                    owner = next((z for z in zones for cx, cy, cid in z.chunks
                                  if z.matrix == mtx and cy * w + cx == i), zone)
                    names[i], _ = conv.chunk(swap[c], owner)
            cells = None
        if cells is not None:
            names = []
            for c in cells:
                if c < 0:
                    names.append(None)
                    continue
                name, _ = conv.chunk(c, zone)
                names.append(name)
        with open('%s/matrices/m%d.json' % (out_dir, new_id), 'w') as f:
            json.dump({'width': w, 'height': h, 'cells': names}, f, separators=(',', ':'))
        table.append((event, mtx, new_id))
        print('map replace: event %d, matrix %d -> %d (%s)' % (event, mtx, new_id, 'matrix' if kind == 1 else 'chunk'))
    with open('src/data/bw_map_replace.h', 'w') as f:
        f.write('// Generated by tools/pokemon_world/bw/mapreplace.py: BW map replacements set by the story\n'
                '// (MapReplaceSetEvent id) -> the BW map matrix and the one drawn instead.\n')
        f.write('static const struct { u8 event; u16 matrix; u16 replacement; } sBwMapReplace[] =\n{\n')
        for t in table:
            f.write('    { %d, %d, %d },\n' % t)
        f.write('};\n')
    return table
