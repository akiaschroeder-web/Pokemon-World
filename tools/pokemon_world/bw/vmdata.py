"""Pokémon World: data for the BW script interpreter (src/bw_script.c).

Pokémon Black's own event scripts run in Unova: the interpreter executes BW's bytecode and does
what it says with our engine (messages, movement, flags, items, battles, warps). This writes:
  data/unova/scripts/<n>.bin   BW's script files (a/0/5/7), the ones zones and global ranges use
  data/unova_bw.s              them, and all of BW's story text (a/0/0/3) in our character set
  src/data/bw_vm_tables.h      zones (script/text files), global script ranges, item/species/move
                               maps, which map holds which BW zone tile, NPC actor ids per map

Global script ids (2000+) are looked up in BW's own table (overlay 10, 46 entries of u16 first,
last, script file, 3, text file), found by searching the overlay for the 3000-4999 -> 863 entry.
"""

import os
import re
import struct

import ndspy.rom

import scripts

GLOBAL_TABLE_MAGIC = struct.pack('<5H', 3000, 4999, 863, 3, 158)
# (overlay 21 offset, item count) of Black's 26 shop lists (UPR-ZX gen5_offsets.ini, ShopItemOffsets/Sizes)
SHOPS = [(0x51538, 2), (0x5153C, 2), (0x51546, 3), (0x5154C, 4), (0x51564, 4), (0x51590, 6), (0x515E4, 7),
         (0x515F2, 7), (0x51600, 8), (0x51610, 8), (0x51620, 8), (0x51630, 8), (0x51640, 8), (0x51650, 9),
         (0x51662, 9), (0x51674, 9), (0x51686, 11), (0x5169C, 11), (0x516B2, 11), (0x516C8, 11), (0x516F8, 14),
         (0x51714, 16), (0x51734, 16), (0x51774, 17), (0x51796, 18), (0x517BA, 19)]


def global_ranges(rom_path):
    rom = ndspy.rom.NintendoDSRom.fromFile(rom_path)
    data = bytes(rom.loadArm9Overlays()[10].data)
    i = data.find(GLOBAL_TABLE_MAGIC)
    if i < 0:
        raise SystemExit('BW global script table not found in overlay 10')

    def ok(o):
        s, e, f, t3, tx = struct.unpack_from('<5H', data, o)
        return 1000 <= s <= e < 20000 and 800 <= f < 900 and t3 == 3
    while ok(i - 10):
        i -= 10
    out = []
    while ok(i):
        s, e, f, _, tx = struct.unpack_from('<5H', data, i)
        out.append((s, e, f, tx))
        i += 10
    return sorted(out)


def const_names(path, prefix):
    return set(re.findall(r'\b(%s[A-Z0-9_]+)\b' % prefix, open(path).read()))


ITEM_FIXES = {'PARLYZ_HEAL': 'PARALYZE_HEAL', 'THUNDERSTONE': 'THUNDER_STONE', 'BLACKGLASSES': 'BLACK_GLASSES',
              'BRIGHTPOWDER': 'BRIGHT_POWDER', 'DEEPSEASCALE': 'DEEP_SEA_SCALE', 'DEEPSEATOOTH': 'DEEP_SEA_TOOTH',
              'NEVERMELTICE': 'NEVER_MELT_ICE', 'SILVERPOWDER': 'SILVER_POWDER', 'TWISTEDSPOON': 'TWISTED_SPOON',
              'ENERGYPOWDER': 'ENERGY_POWDER', 'KINGS_ROCK': 'KINGS_ROCK', 'X_DEFEND': 'X_DEFENSE',
              'X_SPECIAL': 'X_SP_ATK', 'X_SP_DEF': 'X_SP_DEF', 'DOWSING_MCHN': 'DOWSING_MACHINE',
              'POKE_BALL': 'POKE_BALL', 'TM_V_PASS': 'TM_V_PASS'}


def item_const(name, known):
    s = name.replace('é', 'e').replace('É', 'E').upper()
    s = re.sub(r"['.]", '', s)
    s = re.sub(r'[^A-Z0-9]+', '_', s).strip('_')
    s = ITEM_FIXES.get(s, s)
    c = 'ITEM_' + s
    return c if c in known else None


def write(rom, rom_path, zones, maps, places, text_decoder, species_by_dex):
    ranges = global_ranges(rom_path)
    files = rom.narc('a/0/5/7')
    texts = rom.narc('a/0/0/3')
    used_scripts = set(z.scripts for z in zones) | set(z.init_scripts for z in zones) | {f for _, _, f, _ in ranges}
    used_texts = set(z.text for z in zones) | {t for _, _, _, t in ranges}
    os.makedirs('data/unova/scripts', exist_ok=True)
    asm = ['@ Generated by tools/pokemon_world/import_bw.py (bw/vmdata.py): Pokémon Black\'s scripts and text.\n',
           '\t.section .rodata\n', '\t.align 2\n']
    for n in sorted(used_scripts):
        if n >= len(files):
            continue
        with open('data/unova/scripts/%d.bin' % n, 'wb') as f:
            f.write(files[n])
        asm.append('\t.global gBwScript_%d\ngBwScript_%d:\n\t.incbin "data/unova/scripts/%d.bin"\n\t.align 2\n' % (n, n, n))
    strings = 0
    for n in sorted(used_texts):
        if n >= len(texts):
            continue
        lines = text_decoder(texts[n])
        for k, codes in enumerate(lines):
            asm.append('gBwText_%d_%d:\n\t.string "%s$"\n' % (n, k, scripts.to_vm_string(codes)))
        asm.append('\t.align 2\n\t.global gBwTextTable_%d\ngBwTextTable_%d:\n' % (n, n))
        asm += ['\t.4byte gBwText_%d_%d\n' % (n, k) for k in range(len(lines))]
        asm.append('\t.global gBwTextCount_%d\ngBwTextCount_%d:\n\t.4byte %d\n' % (n, n, len(lines)))
        strings += len(lines)
    with open('data/unova_bw.s', 'w', encoding='utf-8') as f:
        f.write(''.join(asm))

    # items: BW id -> our constant, by name (a/0/0/2 file 54)
    item_names = [scripts_plain(s) for s in text_decoder(rom.narc('a/0/0/2')[54])]
    known_items = const_names('include/constants/items.h', 'ITEM_')
    items = [item_const(n, known_items) if n else None for n in item_names]
    missing = sorted({n for n, c in zip(item_names, items) if n and not c})

    c = ['// Generated by tools/pokemon_world/import_bw.py (bw/vmdata.py) - edit that script, not this file.\n',
         '// Tables for the BW script interpreter (src/bw_script.c).\n\n']
    for n in sorted(used_scripts):
        if n < len(files):
            c.append('extern const u8 gBwScript_%d[];\n' % n)
    for n in sorted(used_texts):
        if n < len(texts):
            c.append('extern const u8 *const gBwTextTable_%d[];\nextern const u32 gBwTextCount_%d;\n' % (n, n))
    c.append('\nstatic const struct BwScriptFile sBwScriptFiles[] =\n{\n')
    for n in sorted(used_scripts):
        if n < len(files):
            c.append('    [%d] = { gBwScript_%d, %d },\n' % (n, n, len(files[n])))
    c.append('};\n\nstatic const struct BwTextFile sBwTextFiles[] =\n{\n')
    for n in sorted(used_texts):
        if n < len(texts):
            c.append('    [%d] = { gBwTextTable_%d, &gBwTextCount_%d },\n' % (n, n, n))
    c.append('};\n\nstatic const struct BwGlobalRange sBwGlobalRanges[] =\n{\n')
    for s, e, f, t in ranges:
        c.append('    { %d, %d, %d, %d },\n' % (s, e, f, t))
    c.append('};\n\n// BW zone -> its script file, text file\nstatic const struct BwZone sBwZones[] =\n{\n')
    for z in zones:
        c.append('    [%d] = { %d, %d },\n' % (z.id, z.scripts, z.text))
    c.append('};\n\n// the maps a BW zone is split into: zone, map, rectangle (in BW matrix tiles)\n'
             'static const struct BwZoneMap sBwZoneMaps[] =\n{\n')
    for gm in maps:
        x, y, w, h = gm.rect
        c.append('    { %d, %s, %d, %d, %d, %d },\n' % (gm.zone.id, gm.const, x * 32, y * 32, w * 32, h * 32))
    c.append('};\n\n// BW item id -> ours\nstatic const u16 sBwItems[] =\n{\n')
    for i, it in enumerate(items):
        if it:
            c.append('    [%d] = %s,\n' % (i, it))
    # shop lists: u16 item arrays in overlay 21, no count or end (UPR-ZX's offsets/sizes for Black)
    ovl = bytes(ndspy.rom.NintendoDSRom.fromFile(rom_path).loadArm9Overlays()[21].data)
    flat, offs = [], [0]
    for off, n in SHOPS:
        for k in range(n):
            it = items[struct.unpack_from('<H', ovl, off + 2 * k)[0]] if off + 2 * k + 2 <= len(ovl) else None
            if it:
                flat.append(it)
        offs.append(len(flat))
    c.append('};\n\n// BW\'s shop lists (overlay 21), flattened: list n is sBwShops[sBwShopOffsets[n]..[n + 1]]\n'
             'static const u16 sBwShops[] =\n{\n')
    c += ['    %s,\n' % it for it in flat]
    c.append('};\n\nstatic const u16 sBwShopOffsets[] = {%s};\n' % ', '.join(str(o) for o in offs))
    c.append('\n// National Dex number -> species\nstatic const u16 sBwSpecies[] =\n{\n')
    for dex in sorted(species_by_dex):
        if dex <= 649:
            c.append('    [%d] = %s,\n' % (dex, species_by_dex[dex]))
    c.append('};\n\n// per map: BW NPC uid -> our object event local id\n')
    for gm in maps:
        if gm.actor_ids:
            c.append('static const u8 sBwActors_%s[][2] = {%s};\n' % (
                gm.name, ', '.join('{%d, %d}' % (u, l) for u, l in gm.actor_ids)))
    c.append('\nstatic const struct BwMapActors sBwMapActors[] =\n{\n')
    for gm in maps:
        if gm.actor_ids:
            c.append('    { %s, sBwActors_%s, %d },\n' % (gm.const, gm.name, len(gm.actor_ids)))
    c.append('};\n')
    with open('src/data/bw_vm_tables.h', 'w', encoding='utf-8') as f:
        f.write(''.join(c))
    print('BW scripts: %d files, %d text files (%d strings), %d global ranges; %d BW items have no match yet: %s'
          % (len(used_scripts), len(used_texts), strings, len(ranges), len(missing), ', '.join(missing[:60])))
    return missing


def scripts_plain(codes):
    s = ''
    for c in codes:
        if c == 0xFFFF:
            break
        if c < 0xD800 or c > 0xDFFF:
            s += chr(c) if c < 0xF000 else ''
    return s
