def decode_wave(w):
    """SWAV -> (signed 16-bit samples, loop start or None)."""
    d = w.data
    wt = int(w.waveType)
    if wt == 0:                            # PCM8
        s = [((b ^ 0x80) - 128) * 256 if False else (b - 256 if b > 127 else b) * 256 for b in d]
        ls = w.loopOffset * 4
    elif wt == 1:                          # PCM16
        s = list(struct.unpack('<%dh' % (len(d) // 2), d[:len(d) // 2 * 2]))
        ls = w.loopOffset * 2
    else:                                  # IMA-ADPCM
        if len(d) < 4:
            return [0], None
        hdr = struct.unpack_from('<I', d, 0)[0]
        pcm = hdr & 0xFFFF
        pcm = pcm - 65536 if pcm > 32767 else pcm
        idx = min(88, (hdr >> 16) & 0x7F)
        s = [pcm]
        for b in d[4:]:
            for nib in (b & 15, b >> 4):
                step = IMA_STEP[idx]
                diff = step >> 3
                if nib & 1:
                    diff += step >> 2
                if nib & 2:
                    diff += step >> 1
                if nib & 4:
                    diff += step
                pcm = max(pcm - diff, -0x7FFF) if nib & 8 else min(pcm + diff, 0x7FFF)
                idx = max(0, min(88, idx + IMA_INDEX[nib & 7]))
                s.append(pcm)
        ls = max(0, w.loopOffset * 8 - 8 + 1)
    if not w.isLooped or ls >= len(s):
        return s, None
    return s, ls


def write_wav(path, samples, rate, loop, base_note):
    pitch = round(rate * 1024 * 2 ** ((60 - base_note) / 12))
    data = bytes(max(0, min(255, ((v + 128) >> 8) + 128)) for v in samples)   # 8-bit, as m4a plays it
    fmt = struct.pack('<HHIIHH', 1, 1, rate, rate, 1, 8)
    chunks = b'fmt ' + struct.pack('<I', 16) + fmt
    if loop is not None:
        smpl = struct.pack('<9I', 0, 0, 0, base_note, 0, 0, 0, 1, 0) + struct.pack('<6I', 0, 0, loop, len(samples) - 1, 0, 0)
        chunks += b'smpl' + struct.pack('<I', len(smpl)) + smpl
    chunks += b'agbp' + struct.pack('<I', 4) + struct.pack('<I', pitch)
    chunks += b'data' + struct.pack('<I', len(data)) + data + (b'\0' if len(data) & 1 else b'')   # RIFF pad byte
    with open(path, 'wb') as f:
        f.write(b'RIFF' + struct.pack('<I', 4 + len(chunks)) + b'WAVE' + chunks)


def attack_byte(a):
    a = 0 if a & 0x80 else a
    m = ATTACK_LUT[0x7F - a] if a >= 0x6D else 0xFF - a
    if m == 0:
        return 255
    n = math.log(128 / 92544) / math.log(m / 256)
    frames = n / UPDATES_PER_FRAME
    return 255 if frames <= 1 else max(1, min(255, round(255 / frames)))


def fall_byte(d):
    d = 0 if d & 0x80 else d
    r = 0xFFFF if d == 0x7F else 0x3C00 if d == 0x7E else (2 * d + 1) if d < 0x32 else 0x1E00 // (0x7E - d)
    if r >= 0x3C00:
        return 0
    db = r * UPDATES_PER_FRAME / 1280
    return max(0, min(255, round(256 * 10 ** (-db / 20))))


def sustain_byte(s):
    s = 0x7F if s & 0x80 else s
    return max(0, min(255, round(255 * 10 ** (SUST[s] / 200))))


class Samples:
    def __init__(self, sdat):
        self.sdat = sdat
        self.done = {}           # key -> label
        self.asm = []

    def wave(self, bank, nd):
        """Sample label for a note definition (PCM, PSG square or noise), at its base note."""
        t = int(nd.type)
        base = nd.pitch
        if t == 2:
            duty = nd.waveID & 7
            key = ('sq', duty)
            if key not in self.done:
                n = 32
                high = [(duty + 1) * 4 if duty < 7 else 0][0]
                s = [12000 if i < high else -12000 for i in range(n)]
                self.add(key, 'bw_square_%d' % duty, s, 8372, 0, 60)
            return self.done[key]
        if t == 3:
            key = ('noise',)
            if key not in self.done:
                rnd = random.Random(1)
                self.add(key, 'bw_noise', [rnd.randint(-9000, 9000) for _ in range(8192)], 32768, 0, 60)
            return self.done[key]
        slot = nd.waveArchiveIDID
        if slot >= len(bank.waveArchiveIDs):
            return None
        warc = bank.waveArchiveIDs[slot]
        if warc >= len(self.sdat.waveArchives) or self.sdat.waveArchives[warc][1] is None:
            return None
        waves = self.sdat.waveArchives[warc][1].waves
        if nd.waveID >= len(waves):
            return None
        key = (warc, nd.waveID, base)
        if key not in self.done:
            w = waves[nd.waveID]
            s, ls = decode_wave(w)
            rate = round(16756991 / w.time) if w.time else w.sampleRate
            if rate > MAX_RATE:          # our mixer runs well below this: halve the size, sound the same
                f = rate / MAX_RATE
                n = int(len(s) / f)
                src = s
                s = []
                for i in range(n):                 # average what each new sample covers (less aliasing)
                    a = int(i * f)
                    b = min(len(src), max(a + 1, int((i + 1) * f)))
                    s.append(sum(src[a:b]) // (b - a))
                ls = None if ls is None else min(n - 1, int(ls / f))
                rate = MAX_RATE
            self.add(key, 'bw_%d_%d_%d' % key, s, rate, ls, base)
        return self.done[key]

    def add(self, key, name, s, rate, loop, base):
        os.makedirs(SAMPLE_DIR, exist_ok=True)
        write_wav('%s/%s.wav' % (SAMPLE_DIR, name), s, rate, loop, base)
        label = 'DirectSoundWaveData_' + name
        self.asm.append('\t.align 2\n%s::\n\t.incbin "%s/%s.bin"\n\n' % (label, SAMPLE_DIR, name))
        self.done[key] = label


def voice_line(samples, bank, nd, key_field=60):
    lab = samples.wave(bank, nd)
    if lab is None:
        return DUMMY_VOICE
    return '\tvoice_directsound %d, 0, %s, %d, %d, %d, %d\n' % (
        key_field, lab, attack_byte(nd.attack), fall_byte(nd.decay), sustain_byte(nd.sustain), fall_byte(nd.release))


def voicegroup(name, bank, progs, samples):
    """Our voicegroup for one song: entry i is the bank instrument progs[i]."""
    out, subs = ['voice_group %s\n' % name], []
    for k, prog in enumerate(progs):
        inst = bank.instruments[prog] if prog < len(bank.instruments) else None
        if inst is None:
            out.append(DUMMY_VOICE)
        elif isinstance(inst, ndspy.soundBank.SingleNoteInstrument):
            out.append(voice_line(samples, bank, inst.noteDefinition))
        elif isinstance(inst, ndspy.soundBank.RangeInstrument):          # drum kit: key k plays entry k-first
            sub = '%s_d%d' % (name, k)
            out.append('\tvoice_keysplit_all voicegroup_%s\n' % sub)
            subs.append('voice_group %s, %d\n' % (sub, inst.firstPitch))
            for i, nd in enumerate(inst.noteDefinitions):
                subs.append(voice_line(samples, bank, nd, key_field=inst.firstPitch + i))
        elif isinstance(inst, ndspy.soundBank.RegionalInstrument):       # key split
            sub = '%s_s%d' % (name, k)
            out.append('\tvoice_keysplit voicegroup_%s, keysplit_%s\n' % (sub, sub))
            subs.append('voice_group %s\n' % sub)
            table, lo = [], 0
            for r, reg in enumerate(inst.regions):
                subs.append(voice_line(samples, bank, reg.noteDefinition))
                table += [r] * max(0, reg.lastPitch + 1 - lo)
                lo = reg.lastPitch + 1
            table = (table + [max(0, len(inst.regions) - 1)] * 128)[:128]
            subs.append('\t.global keysplit_%s\nkeysplit_%s:\n\t.byte %s\n' % (sub, sub, ', '.join(map(str, table))))
        else:
            out.append(DUMMY_VOICE)
    if len(progs) == 0:
        out.append(DUMMY_VOICE)
    return ''.join(out) + '\n' + ''.join(subs) + '\n'


