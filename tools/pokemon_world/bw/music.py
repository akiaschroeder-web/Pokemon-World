class Walker:
    """Plays one SSEQ track's events (following jumps, calls and loops) into timed MIDI-ish events."""

    def __init__(self, events, index_of, start):
        self.events, self.index_of, self.pc = events, index_of, start
        self.t = 0
        self.mono = True           # note-wait mode (FSS's default): a note waits for its own length
        self.calls, self.loops = [], []
        self.transpose = 0
        self.vol, self.expr = 127, 127
        self.out = []              # (time, kind, data...)
        self.visited = {}          # event index -> time first reached
        self.loop = None           # (start time, end time) of the first backwards jump

    def run(self, limit_t=None, steps=400000):
        ev = self.events
        while steps > 0 and 0 <= self.pc < len(ev):
            steps -= 1
            e = ev[self.pc]
            if self.pc not in self.visited:
                self.visited[self.pc] = self.t
            if limit_t is not None and self.t >= limit_t:
                return
            nxt = self.pc + 1
            if isinstance(e, sq.RandomSequenceEvent) or isinstance(e, sq.FromVariableSequenceEvent):
                e = self.resolve(e)
                if e is None:
                    self.pc = nxt
                    continue
            if isinstance(e, sq.IfSequenceEvent):
                self.pc = nxt                # the condition flag isn't tracked: take the command
                continue
            if isinstance(e, sq.NoteSequenceEvent):
                key = max(0, min(127, e.type + self.transpose))
                self.out.append((self.t, 'note', key, e.velocity, max(1, e.duration)))
                if self.mono:
                    self.t += e.duration
            elif isinstance(e, sq.RestSequenceEvent):
                self.t += e.duration
            elif isinstance(e, sq.InstrumentSwitchSequenceEvent):
                self.out.append((self.t, 'prog', e.bankID * 128 + e.instrumentID))
            elif isinstance(e, sq.JumpSequenceEvent):
                d = self.index_of.get(id(e.destination))
                if d is None:
                    return
                if d in self.visited and self.loop is None:
                    self.loop = (self.visited[d], self.t)
                    if limit_t is None:
                        return
                nxt = d
            elif isinstance(e, sq.CallSequenceEvent):
                d = self.index_of.get(id(e.destination))
                if d is not None and len(self.calls) < 16:
                    self.calls.append(nxt)
                    nxt = d
            elif isinstance(e, sq.ReturnSequenceEvent):
                if not self.calls:
                    return
                nxt = self.calls.pop()
            elif isinstance(e, sq.BeginLoopSequenceEvent):
                self.loops.append([nxt, e.loopCount])
            elif isinstance(e, sq.EndLoopSequenceEvent):
                if self.loops:
                    lp = self.loops[-1]
                    if lp[1] == 0:           # forever: a loop like a backwards jump
                        if self.loop is None:
                            self.loop = (self.visited.get(lp[0], 0), self.t)
                            if limit_t is None:
                                return
                        nxt = lp[0]
                    else:
                        lp[1] -= 1
                        if lp[1] > 0:
                            nxt = lp[0]
                        else:
                            self.loops.pop()
            elif isinstance(e, sq.EndTrackSequenceEvent):
                return
            elif isinstance(e, sq.MonoPolySequenceEvent):
                self.mono = int(e.value) == 1
            elif isinstance(e, sq.TempoSequenceEvent):
                self.out.append((self.t, 'tempo', e.value))
            elif isinstance(e, sq.PanSequenceEvent):
                self.out.append((self.t, 'cc', 10, max(0, min(127, e.value))))
            elif isinstance(e, sq.TrackVolumeSequenceEvent):
                self.vol = e.value
                self.out.append((self.t, 'vol', self.vol, self.expr))
            elif type(e).__name__ == 'ExpressionSequenceEvent':
                self.expr = e.value
                self.out.append((self.t, 'vol', self.vol, self.expr))
            elif isinstance(e, sq.TransposeSequenceEvent):
                self.transpose = e.value - 256 if e.value > 127 else e.value
            elif type(e).__name__ == 'PortamentoSequenceEvent':       # 0xC4: pitch bend (ndspy's name is off)
                v = e.value - 256 if e.value > 127 else e.value
                self.out.append((self.t, 'bend', v))
            elif type(e).__name__ == 'PortamentoRangeSequenceEvent':  # 0xC5: bend range
                self.out.append((self.t, 'cc', 20, max(0, min(24, e.value))))
            elif type(e).__name__ == 'VibratoDepthSequenceEvent':
                self.out.append((self.t, 'cc', 1, min(127, e.value)))
            elif type(e).__name__ == 'VibratoSpeedSequenceEvent':
                self.out.append((self.t, 'cc', 21, min(127, round(e.value * 1.6))))
            elif type(e).__name__ == 'VibratoTypeSequenceEvent':
                self.out.append((self.t, 'cc', 22, min(2, int(e.value))))
            elif type(e).__name__ == 'VibratoDelaySequenceEvent':
                self.out.append((self.t, 'cc', 26, min(127, round(e.value / UPDATES_PER_FRAME))))
            self.pc = nxt

    def resolve(self, e):
        """A random / from-variable prefix: the command with a middle (random) or zero (variable) value."""
        try:
            sub = e.subType
            if isinstance(e, sq.RandomSequenceEvent):
                val = (e.randMin + e.randMax) // 2
            else:
                val = 0
            if sub == 0x80:
                return sq.RestSequenceEvent(max(0, val))
            if sub < 0x80:
                args = list(getattr(e, 'args', []) or [])
                vel = args[0] if args else 100
                return sq.NoteSequenceEvent(sub, vel, max(1, val))
        except Exception:
            pass
        return None


def vlq(n):
    out = [n & 0x7F]
    n >>= 7
    while n:
        out.insert(0, 0x80 | (n & 0x7F))
        n >>= 7
    return bytes(out)


def to_midi(sseq, prog_map):
    """SSEQ -> (MIDI bytes, used programs in order, loudness). prog_map: program -> our voice index
    (filled in as programs are met)."""
    events = sseq.events
    index_of = {id(e): i for i, e in enumerate(events)}
    starts = {0: 0}
    for e in events:
        if isinstance(e, sq.BeginTrackSequenceEvent):
            i = index_of.get(id(e.firstEvent))
            if i is not None:
                starts[e.trackNumber] = i
    # pass 1: each track's first loop; the song loops where the longest one does
    loop = None
    for tn, st in sorted(starts.items()):
        w = Walker(events, index_of, st)
        w.run()
        if w.loop and (loop is None or w.loop[1] > loop[1]):
            loop = w.loop
    limit = loop[1] if loop else None
    tracks = []
    for tn, st in sorted(starts.items()):
        w = Walker(events, index_of, st)
        w.run(limit_t=limit)
        tracks.append((tn, w.out))

    loud = []
    chunks = []
    for ch, (tn, out) in enumerate(tracks[:16]):
        if ch == 9 and len(tracks) > 9:
            pass
        evs = []                       # (time, order, bytes)
        vol, expr = 127, 127
        for item in out:
            t, kind = item[0], item[1]
            if limit is not None and t >= limit:
                continue
            if kind == 'note':
                key, vel, dur = item[2], item[3], item[4]
                end = t + dur if limit is None else min(t + dur, limit)
                v = max(1, min(127, round(127 * amp(vel))))
                evs.append((t, 2, bytes([0x90 | ch, key, v])))
                evs.append((max(end, t + 1), 0, bytes([0x80 | ch, key, 0])))
                loud.append(amp(vel) * amp(vol) * amp(expr))
            elif kind == 'prog':
                p = prog_map.setdefault(item[2], len(prog_map))
                evs.append((t, 1, bytes([0xC0 | ch, min(127, p)])))
            elif kind == 'vol':
                vol, expr = item[2], item[3]
                evs.append((t, 1, bytes([0xB0 | ch, 7, max(0, min(127, round(127 * amp(vol) * amp(expr))))])))
            elif kind == 'cc':
                evs.append((t, 1, bytes([0xB0 | ch, item[2], item[3]])))
            elif kind == 'bend':
                b = max(0, min(16383, 8192 + item[2] * 64))
                evs.append((t, 1, bytes([0xE0 | ch, b & 0x7F, b >> 7])))
            elif kind == 'tempo':
                us = round(60000000 / max(1, item[2]))
                evs.append((t, 1, b'\xFF\x51\x03' + us.to_bytes(3, 'big')))
        if ch == 0 and loop:
            evs.append((loop[0], 0, b'\xFF\x06\x01['))
            evs.append((loop[1], 3, b'\xFF\x06\x01]'))
        evs.sort(key=lambda x: (x[0], x[1]))
        data, last = b'', 0
        for t, _, b in evs:
            data += vlq(t - last) + b
            last = t
        data += b'\x00\xFF\x2F\x00'
        chunks.append(b'MTrk' + struct.pack('>I', len(data)) + data)
    head = b'MThd' + struct.pack('>IHHH', 6, 1, len(chunks), 48)
    loud.sort()
    level = loud[int(len(loud) * 0.9)] if loud else 0.25
    # length in frames (for fanfares): ticks at 48 per beat, at the first tempo
    tempo = next((it[2] for _, out in tracks for it in out if it[1] == 'tempo'), 120)
    end = max([it[0] + (it[4] if it[1] == 'note' else 0) for _, out in tracks for it in out] or [0])
    frames = math.ceil(end / 48 * 60 / max(1, tempo) * 59.7275) + 4
    return head + b''.join(chunks), level, frames


