def names(rom):
    """SDAT sequence id -> name."""
    sdat = ndspy.soundArchive.SDAT(rom.getFileByName('wb_sound_data.sdat'))
    return [n for n, _ in sdat.sequences]


def song_const(name):
    return 'MUS_BW_' + name[len('SEQ_BGM_'):] if name.startswith('SEQ_BGM_') else 'MUS_BW_' + name[len('SEQ_'):]


def write(rom, seq_names, first_id):
    """Converts the named sequences (SEQ_BGM_*, SEQ_ME_*). Returns {sequence name: MUS_BW_ constant}."""
    sdat = ndspy.soundArchive.SDAT(rom.getFileByName('wb_sound_data.sdat'))
    by_name = {n: (i, s) for i, (n, s) in enumerate(sdat.sequences) if n}
    samples = Samples(sdat)
    vg, cfg, table, consts, lengths = [], [], [], {}, {}
    for name in seq_names:
        if name not in by_name or by_name[name][1] is None:
            continue
        sid, sseq = by_name[name]
        try:
            sseq.parse()
        except Exception as ex:          # ndspy can't read every command (0x82...): leave the song out
            print('music: %s skipped (%s)' % (name, ex))
            continue
        if sseq.bankID >= len(sdat.banks) or sdat.banks[sseq.bankID][1] is None:
            continue
        bank = sdat.banks[sseq.bankID][1]
        prog_map = {}
        try:
            midi, level, frames = to_midi(sseq, prog_map)
        except Exception as ex:          # a sequence we can't read: leave it out
            print('music: %s skipped (%s)' % (name, ex))
            continue
        const = song_const(name)
        label = const.lower()
        group = 'bw_' + label[len('mus_bw_'):]
        progs = [p for p, _ in sorted(prog_map.items(), key=lambda kv: kv[1])]
        vg.append('@ %s (bank %d)\n' % (name, sseq.bankID) + voicegroup(group, bank, progs, samples))
        with open('%s/%s.mid' % (MIDI_DIR, label), 'wb') as f:
            f.write(midi)
        is_me = name.startswith('SEQ_ME_')
        mvl = max(24, min(127, round(127 * 0.38 / max(level, 0.02))))
        cfg.append('%s.mid: -E -R0 -G_%s -V%03d\n' % (label, group, mvl))
        table.append('\tsong %s, %s, 0\n' % (label, 'MUSIC_PLAYER_SE1' if False else 'MUSIC_PLAYER_BGM'))
        consts[name] = const
        lengths[const] = frames
    with open('sound/voicegroups/bw.inc', 'w') as f:
        f.write('@ ' + GEN + '\n@ Pokémon Black\'s instruments: one voicegroup per song.\n\n' + ''.join(vg))
    with open('sound/direct_sound_data_bw.inc', 'w') as f:
        f.write('@ ' + GEN + '\n@ Pokémon Black\'s samples (sound/voicegroups/bw.inc).\n\n' + ''.join(samples.asm))
    with open('%s/midi_bw.cfg' % MIDI_DIR, 'w') as f:
        f.write(''.join(cfg))
    with open('sound/song_table_bw.inc', 'w') as f:
        f.write('@ ' + GEN + '\n@ Pokémon Black\'s songs (ids in include/constants/songs_bw.h)\n' + ''.join(table))
    with open('include/constants/songs_bw.h', 'w') as f:
        f.write('// ' + GEN + '\n#ifndef GUARD_CONSTANTS_SONGS_BW_H\n#define GUARD_CONSTANTS_SONGS_BW_H\n\n'
                '// Pokémon Black\'s songs, numbered after Heart & Soul\'s: sound/song_table_bw.inc stays the\n'
                '// last thing in sound/song_table.inc.\n\n#define BW_SONGS_START (HNS_SONGS_END + 1)\n')
        for k, c in enumerate(consts.values()):
            f.write('#define %-32s (BW_SONGS_START + %d)\n' % (c, k))
        f.write('#define BW_SONGS_END (BW_SONGS_START + %d)\n\n' % (len(consts) - 1))
        f.write('// For the debug menu\'s sound test\n#define BW_SOUND_LIST_BGM \\\n' + ''.join('    X(%s) \\\n' % c for c in consts.values()) + '\n\n#endif\n')
    with open('src/data/bw_fanfares.h', 'w') as f:
        f.write('// ' + GEN + '\n// Pokémon Black\'s fanfares, used in Unova (src/sound.c GetFanfare).\n'
                'static const struct Fanfare sFanfaresBW[ARRAY_COUNT(sFanfares)] = {\n')
        for fan, seq in FANFARES:
            c = consts.get(seq)
            if c:
                f.write('    [%s] = { %s, %d },\n' % (fan, c, min(lengths[c], 420)))
        f.write('};\n')
    print('music: %d of Black\'s songs, %d samples' % (len(consts), len(samples.done)))
    return consts


def write_seasons(consts, seasonal):
    """src/data/bw_season_music.h: songs with spring/summer/autumn/winter versions (BW zones whose
    four BGM numbers differ). seasonal: [(spring, summer, autumn, winter) sequence names]."""
    rows = sorted({tuple(consts.get(n, 'MUS_NONE') for n in four) for four in seasonal if all(n in consts for n in four)})
    with open('src/data/bw_season_music.h', 'w') as f:
        f.write('// ' + GEN + '\n// Unova songs that change with the season: spring, summer, autumn, winter.\n'
                'static const u16 sBwSeasonMusic[][4] =\n{\n')
        for r in rows:
            f.write('    {%s},\n' % ', '.join(r))
        if not rows:
            f.write('    {MUS_NONE, MUS_NONE, MUS_NONE, MUS_NONE},\n')
        f.write('};\n')
