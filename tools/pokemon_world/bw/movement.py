"""Pokémon World: BW's movement codes (the lists ActorCmdExec runs) -> our movement actions.

BW's codes aren't published; they follow Gen 4's (pret/pokeplatinum generated/movement_actions.txt,
pret/pokeheartgold asm/macros/movement.inc), and BW's own scripts agree: 0x0C-0x0F (walk) are by far
the most used, 0x3C-0x42 are delays, 0x45/0x46 and 0x47/0x48 come in pairs (invisible/visible, lock
and unlock facing), 0x4B is the "!" emote. A list entry is u16 code, u16 count (repeat count).
Directions are BW's north, south, west, east.

write_c() makes src/data/bw_movement.h for src/bw_script.c; step() is what tools/pokemon_world's scene
checker (bw/scenes.py) simulates with, so the game and the check can't disagree.
"""

DIR_OURS = [1, 0, 2, 3]          # BW N, S, W, E -> our action order (down, up, left, right)
DELTA = [(0, -1), (0, 1), (-1, 0), (1, 0)]

# (first code, kind, our action for the first direction, tiles moved)
GROUPS = [
    (0x00, 'face', 'MOVEMENT_ACTION_FACE_DOWN', 0),
    (0x04, 'walk', 'MOVEMENT_ACTION_WALK_SLOW_DOWN', 1),          # walk slower
    (0x08, 'walk', 'MOVEMENT_ACTION_WALK_SLOW_DOWN', 1),
    (0x0C, 'walk', 'MOVEMENT_ACTION_WALK_NORMAL_DOWN', 1),
    (0x10, 'walk', 'MOVEMENT_ACTION_WALK_FAST_DOWN', 1),
    (0x14, 'walk', 'MOVEMENT_ACTION_WALK_FASTER_DOWN', 1),
    (0x18, 'face', 'MOVEMENT_ACTION_WALK_IN_PLACE_SLOW_DOWN', 0),  # on the spot, slower
    (0x1C, 'face', 'MOVEMENT_ACTION_WALK_IN_PLACE_SLOW_DOWN', 0),
    (0x20, 'face', 'MOVEMENT_ACTION_WALK_IN_PLACE_NORMAL_DOWN', 0),
    (0x24, 'face', 'MOVEMENT_ACTION_WALK_IN_PLACE_FAST_DOWN', 0),
    (0x28, 'face', 'MOVEMENT_ACTION_WALK_IN_PLACE_FASTER_DOWN', 0),
    (0x2C, 'face', 'MOVEMENT_ACTION_JUMP_IN_PLACE_DOWN', 0),        # jump on the spot, slow
    (0x30, 'face', 'MOVEMENT_ACTION_JUMP_IN_PLACE_DOWN', 0),        # ... fast
    (0x34, 'walk', 'MOVEMENT_ACTION_JUMP_DOWN', 1),                 # jump near
    (0x38, 'walk', 'MOVEMENT_ACTION_JUMP_2_DOWN', 2),               # jump far
    (0x4C, 'walk', 'MOVEMENT_ACTION_WALK_NORMAL_DOWN', 1),          # walk slightly fast
    (0x50, 'walk', 'MOVEMENT_ACTION_WALK_FAST_DOWN', 1),            # walk slightly faster
    (0x54, 'walk', 'MOVEMENT_ACTION_WALK_FASTER_DOWN', 1),          # walk fastest
    (0x58, 'walk', 'MOVEMENT_ACTION_PLAYER_RUN_DOWN', 1),           # run
    (0x60, 'walk', 'MOVEMENT_ACTION_WALK_NORMAL_DOWN', 1),          # walk ever so slightly fast
]
DELAYS = {0x3C: 1, 0x3D: 2, 0x3E: 4, 0x3F: 8, 0x40: 15, 0x41: 16, 0x42: 32}
SINGLE = {0x45: 'MOVEMENT_ACTION_SET_INVISIBLE', 0x46: 'MOVEMENT_ACTION_SET_VISIBLE',
          0x47: 'MOVEMENT_ACTION_LOCK_FACING_DIRECTION', 0x48: 'MOVEMENT_ACTION_UNLOCK_FACING_DIRECTION',
          0x4B: 'MOVEMENT_ACTION_EMOTE_EXCLAMATION_MARK', 0x67: 'MOVEMENT_ACTION_EMOTE_QUESTION_MARK',
          0x99: 'MOVEMENT_ACTION_EMOTE_EXCLAMATION_MARK'}
# one-direction jumps: code -> (direction, action, tiles)
SIDE_JUMPS = {0x5C: (2, 'MOVEMENT_ACTION_JUMP_LEFT', 1), 0x5D: (3, 'MOVEMENT_ACTION_JUMP_RIGHT', 1),
              0x5E: (2, 'MOVEMENT_ACTION_JUMP_2_LEFT', 2), 0x5F: (3, 'MOVEMENT_ACTION_JUMP_2_RIGHT', 2)}


def describe(code):
    """(kind, action expression, direction or None, tiles) for a BW code; kind 'none' = no effect."""
    for first, kind, action, tiles in GROUPS:
        if first <= code < first + 4:
            d = code - first
            return kind, '%s + %d' % (action, DIR_OURS[d]), d, tiles
    if code in DELAYS:
        return 'delay', None, None, DELAYS[code]
    if code in SINGLE:
        return 'single', SINGLE[code], None, 0
    if code in SIDE_JUMPS:
        d, action, tiles = SIDE_JUMPS[code]
        return 'walk', action, d, tiles
    return 'none', None, None, 0


def step(code, count, pos, facing):
    """Simulates one list entry: (tiles visited, new position, new facing)."""
    kind, _, d, tiles = describe(code)
    visited = []
    if kind == 'face':
        facing = d
    elif kind == 'walk':
        facing = d
        for _ in range(max(1, count)):
            for _ in range(tiles):
                pos = (pos[0] + DELTA[d][0], pos[1] + DELTA[d][1])
                visited.append(pos)
    return visited, pos, facing


def write_c(path='src/data/bw_movement.h'):
    rows = []
    for code in range(0x100):
        kind, action, d, val = describe(code)
        k = {'none': 0, 'face': 1, 'walk': 1, 'single': 2, 'delay': 3}[kind]
        rows.append('    [0x%02X] = { %d, %s, %d },\n' % (code, k, action or '0', val if kind == 'delay' else 0))
    with open(path, 'w') as f:
        f.write('// Generated by tools/pokemon_world/bw/movement.py - edit that script, not this file.\n'
                '// BW movement code -> kind (0 none, 1 repeat the action count times, 2 once, 3 delay of n\n'
                '// frames, count times), our action, frames.\n'
                'struct BwMoveCode { u8 kind; u8 action; u8 frames; };\n'
                'static const struct BwMoveCode sBwMoveCodes[0x100] =\n{\n' + ''.join(rows) + '};\n')
