"""Pokémon World: Unova's heal locations (one per Pokémon Center, plus Nuvema Town's house) and the
debug menu's Unova warp list, from the converted maps in data/maps.

A Pokémon Center is a Unova map with BW's Pokémon Center building (map matrix 13 in
src/data/unova_zones.h). Its heal location is the square in front of its door outside (the
outside end of the Center's exit warp, one step south); after a whiteout the player respawns in
front of its nurse (the Center's Nurse Joy object, two squares south of her, across the counter).

Writes the HEAL_LOCATION_UNOVA_* entries of src/data/heal_locations.json and
src/data/bw_debug_warps.h (debug.c's sDebugMenu_Actions_WarpUnova). Run by import_bw.py after
the maps, or alone: python3 tools/pokemon_world/bw/heal.py
"""

import json
import os
import re
from collections import OrderedDict

PC_MATRIX = '13'
NURSE_GFX = 'OBJ_EVENT_GFX_UNOVA_OBJ78'
# BW's story order (Black: Black City, not White Forest)
ORDER = ['NUVEMA_TOWN', 'ACCUMULA_TOWN', 'STRIATON_CITY', 'NACRENE_CITY', 'CASTELIA_CITY', 'NIMBASA_CITY',
         'DRIFTVEIL_CITY', 'MISTRALTON_CITY', 'ICIRRUS_CITY', 'OPELUCID_CITY', 'LACUNOSA_TOWN', 'UNDELLA_TOWN',
         'BLACK_CITY']


def town_of(map_const):
    """MAP_UNOVA_STRIATON_CITY_Z8 -> STRIATON_CITY"""
    s = map_const[len('MAP_UNOVA_'):]
    return re.sub(r'(_Z\d+|_\d+)$', '', s)


def title(town):
    return ' '.join(w.capitalize() for w in town.split('_'))


def main():
    zones = open('src/data/unova_zones.h').read()
    rows = re.findall(r'\{ (MAP_UNOVA_\w+), (\d+), (\d+), (\d+), (\d+) \}', zones)
    centers = [r[0] for r in rows if r[2] == PC_MATRIX]
    maps = {}
    for d in os.listdir('data/maps'):
        if d.startswith('Unova_'):
            j = json.load(open('data/maps/%s/map.json' % d))
            maps[j['id']] = j

    heals = OrderedDict()
    heals['NUVEMA_TOWN'] = OrderedDict([
        ('id', 'HEAL_LOCATION_NUVEMA_TOWN'), ('map', 'MAP_UNOVA_NUVEMA_TOWN'), ('x', 14), ('y', 13),
        ('respawn_map', 'MAP_UNOVA_NUVEMA_TOWN_PLAYERS_HOUSE_1F'), ('respawn_npc', '0'),
        ('respawn_x', 6), ('respawn_y', 9)])
    for pc in centers:
        town = town_of(pc)
        if town not in ORDER or town in heals:
            continue
        j = maps[pc]
        if not j['warp_events']:
            continue          # its door is on a rail (Castelia's plaza), which the converter can't place yet
        exit_warp = j['warp_events'][0]
        outside = maps[exit_warp['dest_map']]
        door = outside['warp_events'][int(exit_warp['dest_warp_id'])]
        nurse = next(i for i, o in enumerate(j['object_events']) if o['graphics_id'] == NURSE_GFX)
        n = j['object_events'][nurse]
        heals[town] = OrderedDict([
            ('id', 'HEAL_LOCATION_UNOVA_' + town), ('map', exit_warp['dest_map']),
            ('x', door['x']), ('y', door['y'] + 1),
            ('respawn_map', pc), ('respawn_npc', str(nurse + 1)),
            ('respawn_x', n['x']), ('respawn_y', n['y'] + 2)])

    hj = json.load(open('src/data/heal_locations.json'), object_pairs_hook=OrderedDict)
    hj['heal_locations'] = [h for h in hj['heal_locations']
                            if not h['id'].startswith('HEAL_LOCATION_UNOVA_') and h['id'] != 'HEAL_LOCATION_NUVEMA_TOWN']
    towns = [t for t in ORDER if t in heals]
    hj['heal_locations'] += [heals[t] for t in towns]
    # written whole, then moved into place (a half-written file breaks the build's jsonproc)
    text = json.dumps(hj, indent=2, ensure_ascii=False) + '\n'
    with open('src/data/heal_locations.json.tmp', 'w', encoding='utf-8') as f:
        f.write(text)
        f.flush()
        os.fsync(f.fileno())
    with open('src/data/heal_locations.json.tmp', encoding='utf-8') as f:
        assert f.read() == text, 'heal_locations.json.tmp did not read back'
    os.replace('src/data/heal_locations.json.tmp', 'src/data/heal_locations.json')

    with open('src/data/bw_debug_warps.h', 'w') as f:
        f.write('// Generated by tools/pokemon_world/bw/heal.py: the debug menu\'s Unova towns (BW\'s story order).\n')
        f.write('static const struct DebugMenuOption sDebugMenu_Actions_WarpUnova[] =\n{\n')
        for t in towns:
            f.write('    { COMPOUND_STRING("%s"), DebugAction_Util_WarpToTown, DEBUG_HEAL_LOCATION(%s) },\n'
                    % (title(t), heals[t]['id']))
        f.write('    { NULL }\n};\n')
    missing = [t for t in ORDER if t not in heals]
    print('unova heal locations: %d%s' % (len(towns), ' (missing: %s)' % ', '.join(missing) if missing else ''))


if __name__ == '__main__':
    main()
