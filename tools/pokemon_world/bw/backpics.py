"""Pokémon World: Pokémon Black's battle back sprites (a/0/7/3).

a/0/7/3 holds six back figures, 8 files each: NCGR (a 10x10-tile copy), NCGR (the 256x128 linear
bitmap the cells use), NCER, NANR, NMCR (5 poses), NMAR (0 standing, 1 the Poké Ball throw: poses
0, 1, 2, 3, 4), an index, NCLR. The figures: 0 Hilbert, 1 Hilda, 2 Professor Juniper, 3 Cheren,
4 Hilbert and 5 Hilda holding the Xtransceiver.

Our battle backs are 4 frames of 64x64 (frame 0 standing, 1-3 the throw). Each frame is the top 80x80
of Black's figure (head down to where Black's message box covers it) shrunk to 64x64 - the same 80 -> 64
as Black's trainer front pictures (trainers.py). Frames 1-3 are throw poses 2, 3, 4 (pose 1 shows
for 4 ticks only).

Writes graphics/trainers/back_pics/unova/<name>.png, src/data/graphics/trainers_unova_back.h (the
pictures, included with trainers_unova_gfx.h) and trainers_unova_back_table.h (gTrainerPicInfo entries).
The constants (TRAINER_PIC_BW_BACK_*) go in include/constants/trainers.h.
"""

import os

import ndspy.narc

import intro as J
import sprites
from trainers import scale_square, splice

NARC = 'a/0/7/3'
FIGURES = {2: 'juniper'}          # the ones the game uses so far: Juniper's catching demonstration
FRAME_POSES = (0, 2, 3, 4)
DIR = 'graphics/trainers/back_pics/unova'
S = 256


class Figure(J.Juniper):
    def __init__(self, files):
        def find(magic, nth=0):
            return [f for f in files if bytes(f[:4]) == magic][nth]
        g = J.ncgr(find(b'RGCN', 1))
        d = g['data']
        self.bm = bytearray(len(d) * 2)
        for i, v in enumerate(d):
            self.bm[2 * i], self.bm[2 * i + 1] = v & 15, v >> 4
        self.bw = 256 if g['tw'] == 0xFFFF else g['tw'] * 8
        self.pal = J.nclr(find(b'RLCN'))[:16]
        self.cells = J.cells(find(b'RECN'))
        self.seqs = J.nanr(find(b'RNAN'))
        self.poses = J.nmcr(find(b'RCMN'))
        self.anims = J.nanr(find(b'RAMN'))


def write(rom):
    fs = [J.dec(f) for f in ndspy.narc.NARC(rom.rom.getFileByName(NARC)).files]
    os.makedirs(DIR, exist_ok=True)
    gfx = ['// Generated by tools/pokemon_world/bw/backpics.py: Pokémon Black\'s battle back sprites.\n']
    tab = ['// Generated by tools/pokemon_world/bw/backpics.py. Included inside gTrainerPicInfo.\n']
    enum = []
    for k, name in sorted(FIGURES.items()):
        fig = Figure(fs[k * 8:(k + 1) * 8])
        imgs = [fig.compose(p, None, S) for p in FRAME_POSES]
        # one 80x80 window for all frames: from the top of the head, centred on what of the standing
        # figure is inside it
        top = min(J.crop_box([im], S)[1] for im in imgs)
        xs = [i % S for i, v in enumerate(imgs[0]) if v and top <= i // S < top + 80]
        left = (min(xs) + max(xs) + 1) // 2 - 40
        frames = []
        for im in imgs:
            sub = bytearray(80 * 80)
            for y in range(80):
                for x in range(80):
                    X, Y = left + x, top + y
                    if 0 <= X < S and 0 <= Y < S:
                        sub[y * 80 + x] = im[Y * S + X]
            frames.append(scale_square(bytes(sub), 80, fig.pal))
        path = '%s/%s.png' % (DIR, name)
        sprites.png_indexed(path, 64, 64 * len(frames), [b''.join(frames)], fig.pal)
        camel = 'BwBack' + name.capitalize()
        const = 'TRAINER_PIC_BW_BACK_' + name.upper()
        enum.append('    %s,\n' % const)
        gfx.append('const u8 gTrainerBackPic_%s[] = INCGFX_U8("%s", ".4bpp");\n'
                   'const u16 gTrainerBackPicPalette_%s[] = INCGFX_U16("%s", ".gbapal");\n' % (camel, path, camel, path))
        tab.append('    [%s] =\n    {\n        .backPic = TRAINER_BACK_PIC(4, gTrainerBackPic_%s, gTrainerBackPicPalette_%s, sBackAnims_Hoenn),\n    },\n'
                   % (const, camel, camel))
    with open('src/data/graphics/trainers_unova_back.h', 'w') as f:
        f.write(''.join(gfx))
    with open('src/data/graphics/trainers_unova_back_table.h', 'w') as f:
        f.write(''.join(tab))
    splice('include/constants/trainers.h', 'UNOVA_BACK_PICS', ''.join(enum),
           '    TRAINER_PIC_COUNT,', "Pokémon Black's battle back sprites")
