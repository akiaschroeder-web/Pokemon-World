SIZES = {'byte': 1, 'ushort': 2, 'const ushort': 2, 'ref ushort': 2, 'fx16': 2, 'int': 4, 'fx32': 4}
HERE = os.path.dirname(os.path.abspath(__file__))


def fixed_types(nbytes):
    return ['ushort'] * (nbytes // 2) + (['byte'] if nbytes % 2 else [])


def param_types():
    """{opcode: [parameter type]} with FIXES applied."""
    meta = json.load(open(os.path.join(HERE, 'bw_script_commands.json')))
    out = {int(k): [p['Type'] for p in v['params']] for k, v in meta.items()}
    for op, n in FIXES.items():
        out[op] = fixed_types(n)
    return out


def write_header(path='src/data/bw_param_sizes.h'):
    types = param_types()
    with open(path, 'w') as f:
        f.write('// Generated by tools/pokemon_world/bw/param_sizes.py from bw_script_commands.json (PokeScriptSDK5\'s BW\n'
                '// command list) with its corrections: the sizes of each BW script command\'s parameters, so\n'
                '// commands the interpreter doesn\'t do can be skipped.\n')
        f.write('static const u8 sBwParamSizes[][12] =\n{\n')
        for op in sorted(types):
            f.write('    [0x%X] = {%s},\n' % (op, ', '.join([str(SIZES[t]) for t in types[op]] + ['0'])))
        f.write('};\n')


if __name__ == '__main__':
    write_header()
