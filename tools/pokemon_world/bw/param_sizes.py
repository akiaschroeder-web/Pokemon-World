"""Pokémon World: the real parameter sizes of Pokémon Black's script commands.

bw_script_commands.json (PokeScriptSDK5's list, via CTRMapV) guesses the parameters of many commands
it has no documentation for, and some guesses are wrong: CMD_24F has no parameters, not six, so
reading Nuvema Town's "leaving the house" script with the list's sizes runs into garbage and
the game hangs. The sizes below were checked two ways (2026-11-26):
  - the command's handler in Black's code (the table at 0x0217062C in overlay 10): the calls
    to the script readers (u16 0x02011330, u32 0x0201134C, variable 0x02159AE8 / 0x02159B10)
    and inline byte reads;
  - Black's own scripts: decoding every use of the command with each candidate size, the size
    after which the next instructions read as ordinary commands wins (ties: the handler's).
FIXES: opcode -> total bytes of parameters (2-byte parameters, a trailing byte if odd).

Writes src/data/bw_param_sizes.h (how the interpreter skips commands it doesn't do);
scripts.commands() applies FIXES for the converter. Run: python3 tools/pokemon_world/bw/param_sizes.py
"""

