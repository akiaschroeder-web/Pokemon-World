"""Pokémon World: Heart & Soul's HGSS music, for import_hns.py (stage 4 of the Johto import).

Brings over the HGSS songs Heart & Soul uses: the ones its maps and scripts play, plus
ENGINE_SONGS, the ones our C code plays in Johto and the later Kanto (battle, victory, trainer
encounter, fanfare and radio themes). Only songs Heart & Soul builds with its HGSS voicegroup
are brought over; anything else keeps a stand-in (import_hns.py MUSIC_STANDIN).

Heart & Soul keeps the HGSS instruments in its voicegroup229 ("HGSS main") and the groups after
it (instruments split by key, drums). A program or drum key past the end of one group runs on
into the next, so those groups are written together, in Heart & Soul's order. Its samples are
.aif files (made into .bin by aif2pcm); here they become .wav files that wav2agb turns into the
same sample data (header, loop and pitch as aif2pcm made them).

Writes (all generated: edit this script, not the output):
  sound/songs/midi/mus_hg_*.mid          Heart & Soul's MIDI files
  sound/songs/midi/midi_hns.cfg          their mid2agb options (audio_rules.mk reads it after midi.cfg)
  include/constants/songs_hns.h          MUS_HG_* ids, numbered after all our songs (songs.h includes it)
  sound/song_table_hns.inc               their song table entries (song_table.inc includes it last)
  sound/voicegroups/hgss.inc             voicegroup_hgss and the groups it uses, keysplit_hgss_* tables
  sound/direct_sound_data_hgss.inc       DirectSoundWaveData_* for the HGSS samples
  sound/direct_sound_samples/hgss/*.wav  the samples
Heart & Soul's files are only read, never built or run.
"""
