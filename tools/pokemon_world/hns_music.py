# samples: .aif (Heart & Soul) -> .wav (ours)

def _extended(b):
    """IEEE 754 80-bit float (AIFF sample rate)."""
    exp = ((b[0] & 0x7F) << 8) | b[1]
    mant = int.from_bytes(b[2:10], "big")
    if exp == 0 and mant == 0:
        return 0.0
    v = mant * 2.0 ** (exp - 16383 - 63)
    return -v if b[0] & 0x80 else v


def read_aif(path):
    """What aif2pcm reads: (sample rate, looped, loop start, sample count, signed 8-bit samples)."""
    d = open(path, "rb").read()
    if d[:4] != b"FORM" or d[8:12] != b"AIFF":
        sys.exit(f"{path}: not an AIFF file")
    pos, markers, loop_ids, rate, frames, size, data = 12, {}, None, 0.0, 0, 8, b""
    while pos + 8 < len(d):
        cid, n = d[pos:pos + 4], struct.unpack(">I", d[pos + 4:pos + 8])[0]
        c = d[pos + 8:pos + 8 + n]
        pos += 8 + n
        if cid == b"COMM":
            ch, frames, size = struct.unpack(">hIh", c[:8])
            if ch != 1 or size not in (8, 16):
                sys.exit(f"{path}: {ch} channels, {size}-bit (need mono 8/16-bit)")
            rate = _extended(c[8:18])
        elif cid == b"MARK":
            k, p = struct.unpack(">H", c[:2])[0], 2
            for _ in range(k):
                mid, mpos = struct.unpack(">HI", c[p:p + 6])
                ln = c[p + 6]
                p += 7 + ln + (0 if ln & 1 else 1)
                markers[mid] = mpos
        elif cid == b"INST":
            mode, start, end = struct.unpack(">HHH", c[8:14])
            if mode:
                loop_ids = (start, end)
        elif cid == b"SSND":
            data = c[8:]
        # (aif2pcm ignores the other chunks too)
    if size == 16:
        data = bytes(data[i] for i in range(0, len(data) - 1, 2))  # high byte of each big-endian sample
    count, looped, loop_start = frames, False, 0
    if markers and loop_ids:
        if loop_ids[0] in markers:
            loop_start, looped = markers[loop_ids[0]], True
        if loop_ids[1] in markers:
            if markers[loop_ids[1]] < loop_start:
                loop_start, looped = markers[loop_ids[1]], True
            count = markers[loop_ids[1]]
    return rate, looped, loop_start, count, data


def read_wav(path):
    """Our .wav samples, in the same terms as read_aif (None if it can't be read)."""
    try:
        d = open(path, "rb").read()
    except OSError:
        return None
    pos, rate, looped, loop_start, loop_end, pitch, data = 12, 0, False, 0, 0, None, b""
    while pos + 8 <= len(d):
        cid, n = d[pos:pos + 4], struct.unpack("<I", d[pos + 4:pos + 8])[0]
        c = d[pos + 8:pos + 8 + n]
        pos += 8 + n + (n & 1)
        if cid == b"fmt ":
            rate = struct.unpack("<I", c[4:8])[0]
        elif cid == b"smpl" and struct.unpack("<I", c[28:32])[0]:
            looped = True
            loop_start, loop_end = struct.unpack("<II", c[44:52])
        elif cid == b"agbp":
            pitch = struct.unpack("<I", c[:4])[0]
        elif cid == b"data":
            data = bytes(b ^ 0x80 for b in c)
    return (pitch if pitch is not None else int(rate * 1024)), looped, loop_start, (loop_end + 1 if looped else len(data)), data


def _write_wav():
    """expansion's bin_to_wav writer, plus the "agbl" chunk our samples carry: the sample's last
    index (aif2pcm's end field, sample count - 1), which wav2agb writes instead of the count."""
    spec = importlib.util.spec_from_file_location("bin_to_wav", "migration_scripts/1.14/bin_to_wav.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)

    def write(path, rate, looped, loop_start, loop_end, samples):
        m.write_wav(path, rate, looped, loop_start, loop_end, samples)
        d = bytearray(open(path, "rb").read())
        p = 12
        while d[p:p + 4] != b"data":  # before the data chunk, like our other samples
            n = struct.unpack("<I", d[p + 4:p + 8])[0]
            p += 8 + n + (n & 1)
        d[p:p] = b"agbl" + struct.pack("<II", 4, len(samples) - 1)
        d[4:8] = struct.pack("<I", len(d) - 8)
        open(path, "wb").write(bytes(d))
    return write


