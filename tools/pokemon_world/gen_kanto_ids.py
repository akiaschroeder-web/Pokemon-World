#!/usr/bin/env python3
"""Pokémon World: give FireRed's Kanto its own flags, variables and trainer IDs.

FireRed's flag, var and trainer numbers overlap Emerald's (Hoenn and Sinnoh). For the
Emerald build this writes three headers that keep FireRed's names but move them into
Kanto's own ranges (stored in SaveBlock3, see include/constants/flags.h and vars.h):

  include/constants/flags_kanto.h      replaces the FRLG stub block in flags.h
  include/constants/vars_kanto.h       used instead of vars_frlg.h
  include/constants/opponents_kanto.h  used instead of opponents_frlg.h

Run from the repo root (needs a host gcc to read FireRed's flag values):
    python3 tools/pokemon_world/gen_kanto_ids.py
"""
import os, re, subprocess, sys, tempfile

GEN = "// Generated by tools/pokemon_world/gen_kanto_ids.py - edit that script, not this file.\n"

# Flags and vars shared by name with Hoenn that Kanto needs its own copy of.
# The Kanto scripts already use these KT_ names.
KANTO_ONLY_FLAGS = ["FLAG_KT_SYS_GAME_CLEAR", "FLAG_KT_HIDE_DEOXYS", "FLAG_KT_HIDE_HO_OH",
                    "FLAG_KT_HIDE_LUGIA", "FLAG_KT_HIDDEN_ITEM_VICTORY_ROAD_1F_ULTRA_BALL",
                    "FLAG_KT_DEOXYS_ROCK_COMPLETE", "FLAG_KT_IS_CHAMPION"]
KANTO_ONLY_VARS = ["VAR_KT_STARTER_MON"]

KANTO_FLAG_SLOTS = 0x400
KANTO_VAR_SLOTS = 0xE0


def read(p):
    return open(p, encoding="utf-8").read()


def frlg_values(names):
    """Evaluate FireRed flag values with the host compiler."""
    src = '#include "config/general.h"\n#include "constants/global.h"\n#include "constants/flags.h"\n#include <stdio.h>\nint main(void){\n'
    for n in names:
        src += f'#ifdef {n}\nprintf("{n} %ld\\n",(long)({n}));\n#endif\n'
    src += "return 0;}\n"
    d = tempfile.mkdtemp()
    c = os.path.join(d, "v.c")
    open(c, "w").write(src)
    exe = os.path.join(d, "v")
    r = subprocess.run(["gcc", "-w", "-std=gnu17", "-DFIRERED", "-DMODERN=1", "-DTESTING=0",
                        "-iquote", "include", "-iquote", "gflib", "-o", exe, c], capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stderr)
    out = subprocess.run([exe], capture_output=True, text=True).stdout
    return {l.split()[0]: int(l.split()[1]) for l in out.splitlines()}


def stub_block(text):
    start = text.index("// FRLG flags\n")
    end = text.index("\n#endif", start)
    return start, end


def gen_flags():
    flags_h = read("include/constants/flags.h")
    if "#include \"constants/flags_kanto.h\"" in flags_h:
        names = re.findall(r"(?m)^#define (FLAG_\w+)", read("include/constants/flags_kanto.h"))
        names = [n for n in names if n not in KANTO_ONLY_FLAGS]
    else:
        s, e = stub_block(flags_h)
        names = re.findall(r"(?m)^#define (FLAG_\w+)", flags_h[s:e])
    vals = frlg_values(names)
    slot_of, slots = {}, 0
    for v in sorted({vals[n] for n in names if vals.get(n, 0)}):
        slot_of[v] = slots
        slots += 1
    out = [GEN, "#ifndef GUARD_CONSTANTS_FLAGS_KANTO_H", "#define GUARD_CONSTANTS_FLAGS_KANTO_H", "",
           "// FireRed's Kanto flags, moved into Kanto's own range. Same names as in FireRed.", ""]
    for n in names:
        v = vals.get(n, 0)
        out.append(f"#define {n:<64} " + (f"(KANTO_FLAGS_START+0x{slot_of[v]:03X})" if v else "0"))
    out += ["", "// Flags Hoenn also has under the same name; Kanto keeps its own."]
    for n in KANTO_ONLY_FLAGS:
        out.append(f"#define {n:<64} (KANTO_FLAGS_START+0x{slots:03X})")
        slots += 1
    assert slots <= KANTO_FLAG_SLOTS, slots
    out += ["", f"#define KANTO_FLAGS_USED 0x{slots:03X}", "", "#endif // GUARD_CONSTANTS_FLAGS_KANTO_H", ""]
    open("include/constants/flags_kanto.h", "w").write("\n".join(out))
    return slots


def gen_vars():
    src = read("include/constants/vars_frlg.h")
    emerald = set(re.findall(r"(?m)^#define (VAR_\w+)", read("include/constants/vars.h")))
    slot_of, slots = {}, 0

    def sub(m):
        nonlocal slots
        name, val = m.group(1), m.group(2)
        v = int(val, 0)
        if not (0x4000 <= v <= 0x40FF) or name in emerald:
            return m.group(0)
        if v not in slot_of:
            slot_of[v] = slots
            slots += 1
        return f"#define {name} (KANTO_VARS_START+0x{slot_of[v]:02X}) // FireRed 0x{v:04X}"

    body = re.sub(r"(?m)^#define (VAR_\w+)\s+(0x[0-9A-Fa-f]+|\d+)\b.*$", sub, src)
    body = body.replace("GUARD_CONSTANTS_VARS_FRLG_H", "GUARD_CONSTANTS_VARS_KANTO_H")
    extra = ["", "// Vars Hoenn also has under the same name; Kanto keeps its own."]
    for n in KANTO_ONLY_VARS:
        extra.append(f"#define {n} (KANTO_VARS_START+0x{slots:02X})")
        slots += 1
    extra.append(f"#define KANTO_VARS_USED 0x{slots:02X}")
    assert slots <= KANTO_VAR_SLOTS, slots
    i = body.rindex("#endif")
    body = body[:i] + "\n".join(extra) + "\n\n" + body[i:]
    open("include/constants/vars_kanto.h", "w").write(GEN + body)
    return slots


def gen_trainers():
    src = read("include/constants/opponents_frlg.h")

    def sub(m):
        name, v = m.group(1), int(m.group(2))
        if v == 0:
            return m.group(0)
        return f"#define {name:<42} (KANTO_TRAINERS_START+{v - 1})"

    body = re.sub(r"(?m)^#define (TRAINER_\w+)\s+(\d+)\s*$", sub, src)
    body = body.replace("GUARD_CONSTANTS_OPPONENTS_FRLG_H", "GUARD_CONSTANTS_OPPONENTS_KANTO_H")
    open("include/constants/opponents_kanto.h", "w").write(GEN + body)


if __name__ == "__main__":
    f = gen_flags()
    v = gen_vars()
    gen_trainers()
    print(f"Kanto: {f} flags, {v} vars")
