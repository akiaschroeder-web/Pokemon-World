            name = re.search(r'_\("([^"]*)"\)', f.get("trainerName", '_("???")'))
            name = name.group(1) if name else "???"
            if "{" in name:
                note("trainer names with a placeholder (Heart & Soul shows the rival's name; TODO)", f"{n}: {name}")
                name = re.sub(r"\{[^}]*\}", "SILVER", name)
            cls = f.get("trainerClass", "TRAINER_CLASS_PKMN_TRAINER_1").strip().rstrip(",")
            if cls not in classes:
                alt = cls + "_FRLG" if cls + "_FRLG" in classes else "TRAINER_CLASS_PKMN_TRAINER_1"
                note("trainer classes with a stand-in", f"{cls} -> {alt}")
                cls = alt
            pic = f.get("trainerPic", "TRAINER_PIC_YOUNGSTER").strip().rstrip(",")
            if pic not in pics:
                alt = pic + "_FRLG" if pic + "_FRLG" in pics else "TRAINER_PIC_YOUNGSTER"
                note("trainer pics with a stand-in", f"{pic} -> {alt}")
                pic = alt
            female = "F_TRAINER_FEMALE" in f.get("encounterMusic_gender", "")
            dbl = "TRUE" in f.get("doubleBattle", "FALSE")
            pm = re.search(r"\((sParty_\w+)\)", f.get("party", ""))
            mons = parties.get(pm.group(1)) if pm else None
