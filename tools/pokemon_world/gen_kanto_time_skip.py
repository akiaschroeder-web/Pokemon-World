"""Pokémon World: the table behind Kanto's time skip (FireRed's Kanto -> Heart & Soul's).

After Johto's story ends (FLAG_PW_KANTO_TIME_SKIP), every way into FireRed's Kanto leads
to the matching Gold/Silver-era map instead (src/kanto_time_skip.c does that at warp time).
This writes the FireRed -> Heart & Soul map correspondence it uses:

  src/data/kanto_time_skip.h   sKantoTimeSkipMaps (FireRed map -> Heart & Soul map) and
                               sKantoTimeSkipHeals (FireRed heal location -> Heart & Soul's)

How each FireRed mainland-Kanto map is matched (the Sevii Islands, Navel Rock, Birth Island
and the link rooms are left alone, they stay FireRed's):
  1. "exact":  same map name (PalletTown_Frlg -> PalletTown_Hns), unless listed in NOT_SAME
  2. "alias":  the hand-made ALIAS table below (different names, same place)
  3. "center": X_PokemonCenter_1F/2F -> X_PokemonCenter (Heart & Soul's centers have one floor)
  4. "door":   a building with no counterpart: the Heart & Soul building whose door is at
               about the same place in the matched town/route (positions scaled to its size)
  5. "parent": otherwise the map it's in (the town/route/cave its first warp leads to),
               so you land at the nearest sensible place.
Run from the repo root after the FireRed or Heart & Soul maps change:
    python3 tools/pokemon_world/gen_kanto_time_skip.py
"""
